def _k(image: Image, name: str) -> str:
    dll = "shell32.dll" if name == "CommandLineToArgvW" else "kernel32.dll"
    return image.iat_symbol(dll, name)


def _i64(asm, reg: int, value: int) -> None:
    asm.mov_reg_imm64(reg, value & 0xFFFFFFFFFFFFFFFF)


def _pop(asm) -> None:
    asm.dec_mem(RBP, SP)
    asm.mov_reg_mem(RAX, RBP, SP)
    asm.shl_reg_imm8(RAX, 5)
    asm.mov_reg_mem(RBX, RBP, CELLS)
    asm.add_reg(RBX, RAX)


def _slot(asm) -> None:
    asm.mov_reg_mem(RAX, RBP, SP)
    asm.shl_reg_imm8(RAX, 5)
    asm.mov_reg_mem(RBX, RBP, CELLS)
    asm.add_reg(RBX, RAX)
    asm.inc_mem(RBP, SP)


def _push_i64(asm) -> None:
    # value in r12
    _slot(asm)
    asm.xor_reg(RAX, RAX)
    asm.mov_mem_reg(RBX, 0, RAX)
    asm.mov_mem_reg(RBX, 8, R12)
    asm.mov_mem_reg(RBX, 16, RAX)
    asm.mov_mem_reg(RBX, 24, RAX)


def _push_bytes(asm) -> None:
    # ptr r12, len r13, tag in r14
    _slot(asm)
    asm.mov_mem_reg(RBX, 0, R14)
    asm.mov_mem_reg(RBX, 8, R12)
    asm.mov_mem_reg(RBX, 16, R13)
    asm.xor_reg(RAX, RAX)
    asm.mov_mem_reg(RBX, 24, RAX)


def _push_bytes_tag(asm, tag: int) -> None:
    _i64(asm, R14, tag)
    _push_bytes(asm)


def _fail_empty(asm) -> None:
    _i64(asm, RAX, 1)
    asm.mov_mem_reg(RBP, FAILED, RAX)
    asm.mov_reg_mem(RAX, RBP, EMPTY_P)
    asm.mov_mem_reg(RBP, REASON_P, RAX)
    asm.xor_reg(RAX, RAX)
    asm.mov_mem_reg(RBP, REASON_N, RAX)


def _fail_r12(asm) -> None:
    # reason ptr r12 len r13
    _i64(asm, RAX, 1)
    asm.mov_mem_reg(RBP, FAILED, RAX)
    asm.mov_mem_reg(RBP, REASON_P, R12)
    asm.mov_mem_reg(RBP, REASON_N, R13)


def _read_u16(asm) -> None:
    asm.mov_reg_mem(RDX, RBP, IP)
    asm.movzx_reg_word_mem(RCX, RDX, 0)
    asm.add_mem_imm8(RBP, IP, 2)


def _read_u8(asm) -> None:
    asm.mov_reg_mem(RDX, RBP, IP)
    asm.movzx_reg_byte_mem(RCX, RDX, 0)
    asm.inc_mem(RBP, IP)


def _read_i32(asm) -> None:
    asm.mov_reg_mem(RDX, RBP, IP)
    asm.movsxd_reg_mem(RCX, RDX, 0)
    asm.add_mem_imm8(RBP, IP, 4)


def _kstack(asm) -> None:
    asm.mov_reg_mem(RSP, RBP, KSP)


def _exit(asm, image: Image, code: int) -> None:
    _kstack(asm)
    asm.mov_reg_imm32(RCX, code)
    asm.call_rip(_k(image, "ExitProcess"))
    asm.int3()


def build_exe(image: Compiled) -> bytes:
    pe = Image()
    pe.imports = [
        ("kernel32.dll", KERNEL),
        ("shell32.dll", ["CommandLineToArgvW"]),
    ]
    pe.blob("empty", b"\0")
    pe.blob("nl", b"\n")
    pe.blob("oom", b"out of memory\n")
    pe.blob("depthmsg", b"call depth\n")
    pe.blob("chr0", b"0")
    pe.blob("mindec", b"-9223372036854775808")
    fprint.reserve(pe)
    blobs: dict[int, str] = {}
    for index, (kind, value) in enumerate(image.consts):
        if kind == "bytes":
            name = f"s{index}"
            pe.blob(name, bytes(value))  # type: ignore[arg-type]
            blobs[index] = name
    pe.blob("prog", image.code)
    pe.blob("header", bytes(512))
    pe.blob("optab", bytes(OPCOUNT * 8))
    pool_n = max(len(image.consts), 1)
    pe.blob("pool", bytes(pool_n * 32))
    func_bytes = bytearray()
    for func in image.funcs:
        func_bytes += struct.pack("<QQQ", func.off, func.nparams, func.nlocals)
    pe.blob("funcs", bytes(func_bytes))
    pe.blob("entry_rva", bytes(8))
    asm = pe.code
    names = ["bad_op"] * OPCOUNT
    handlers = {
        HALT: "op_halt",
        WRITE: "op_write",
        FAIL_EXIT: "op_fail",
        BYTE: "op_make_byte",
        SAVE: "op_save",
        PUSH_CONST: "op_push_const",
        POP_LOCAL: "op_pop_local",
        PUSH_LOCAL: "op_push_local",
        JUMP: "op_jump",
        JZ: "op_jz",
        SET_BYTE: "op_set_byte",
        IF_FAIL: "op_if_fail",
        CLEAR_FAIL: "op_clear",
        ADD: "op_add",
        SUB: "op_sub",
        MUL: "op_mul",
        DIV: "op_div",
        NEG: "op_neg",
        CMP: "op_cmp",
        CAT: "op_cat",
        I64_PARSE: "op_i64",
        ARGC: "op_argc",
        ARG: "op_arg",
        OPEN: "op_open",
        BYTE_AT: "op_byte",
        BYTES_LEN: "op_len",
        LINE_VIEW: "op_line",
        FIELD_N: "op_field_n",
        FIELD_TEXT: "op_field_text",
        PUSH_REASON: "op_reason",
        CALL: "op_call",
        RET: "op_ret",
        RET_FAIL: "op_ret_fail",
        DEC: "op_dec",
        BEFORE: "op_before",
        AFTER: "op_after",
        HOLDS: "op_holds",
        FADD: "op_fadd",
        FSUB: "op_fsub",
        FMUL: "op_fmul",
        FDIV: "op_fdiv",
        FNEG: "op_fneg",
        FCMP: "op_fcmp",
        FFROM: "op_ffrom",
        FTOI: "op_ftoi",
        LIST_NEW: "op_list_new",
        LIST_PUSH: "op_list_push",
        LIST_AT: "op_list_at",
        LIST_LEN: "op_list_len",
        STRUCT_NEW: "op_struct_new",
        FIELD: "op_field",
        MAP_NEW: "op_map_new",
        MAP_PUT: "op_map_put",
        MAP_GET: "op_map_get",
        MAP_HAS: "op_map_has",
        MAP_LEN: "op_map_len",
        MAP_KEY: "op_map_key",
    }
    for opcode, name in handlers.items():
        names[opcode] = name
    _startup(asm, pe, image)
    _helpers(asm, pe)
    _ops(asm, pe)
    asm.label("bad_op")
    asm.mov_reg_mem(RCX, RBP, LASTOP)
    asm.add_reg_imm8(RCX, 100)
    _kstack(asm)
    asm.call_rip(_k(pe, "ExitProcess"))
    asm.int3()
    pe.set_blob("entry_rva", struct.pack("<Q", TEXT_RVA + asm.labels["start"]))
    optab = bytearray()
    for name in names:
        optab += struct.pack("<Q", TEXT_RVA + asm.labels[name])
    pe.set_blob("optab", bytes(optab))
    pool = bytearray()
    if not image.consts:
        pool += bytes(32)
    for index, (kind, value) in enumerate(image.consts):
        if kind == "i64":
            pool += struct.pack("<QQQQ", 0, int(value) & 0xFFFFFFFFFFFFFFFF, 0, 0)  # type: ignore[arg-type]
        elif kind == "f64":
            pool += struct.pack("<QQQQ", TAG_F64, int(value) & 0xFFFFFFFFFFFFFFFF, 0, 0)  # type: ignore[arg-type]
        else:
            pool += struct.pack("<QQQQ", TAG_BYTES | 0x100, pe.blob_rva(blobs[index]), len(value), 0)  # type: ignore[arg-type]
    pe.set_blob("pool", bytes(pool))
    return pe.link("start")


def _startup(asm, pe: Image, image: Compiled) -> None:
    main = image.funcs[image.main]
    asm.label("start")
    asm.and_rsp_align()
    asm.sub_rsp_imm32(0x100)
    asm.lea_rip(RBP, "header")
    asm.mov_mem_reg(RBP, KSP, RSP)
    asm.lea_rip(RAX, "start")
    asm.mov_reg_rip(RCX, "entry_rva")
    asm.sub_reg(RAX, RCX)
    asm.mov_mem_reg(RBP, BASE, RAX)
    asm.lea_rip(RBX, "optab")
    asm.mov_reg_imm32(RCX, OPCOUNT)
    asm.label("fix_optab")
    asm.mov_reg_mem(RAX, RBX, 0)
    asm.mov_reg_mem(RDX, RBP, BASE)
    asm.add_reg(RAX, RDX)
    asm.mov_mem_reg(RBX, 0, RAX)
    asm.add_reg_imm8(RBX, 8)
    asm.dec_reg(RCX)
    asm.jnz("fix_optab")
    asm.lea_rip(RBX, "pool")
    asm.mov_mem_reg(RBP, POOL, RBX)
    _i64(asm, RCX, len(image.consts))
    asm.mov_mem_reg(RBP, NPOOL, RCX)
    asm.label("fix_pool")
    asm.test_reg(RCX, RCX)
    asm.jz("fix_pool_done")
    asm.mov_reg_mem(RAX, RBX, 0)
    _i64(asm, RDX, 0x100)
    asm.test_reg(RAX, RDX)
    asm.jz("fix_pool_next")
    asm.mov_reg_mem(RAX, RBX, 8)
    asm.mov_reg_mem(RDX, RBP, BASE)
    asm.add_reg(RAX, RDX)
    asm.mov_mem_reg(RBX, 8, RAX)
    asm.mov_reg_mem(RAX, RBX, 0)
    _i64(asm, RDX, 0xFFFFFFFFFFFFFEFF)
    asm.and_reg(RAX, RDX)
    asm.mov_mem_reg(RBX, 0, RAX)
    asm.label("fix_pool_next")
    asm.add_reg_imm8(RBX, 32)
    asm.dec_reg(RCX)
    asm.jmp_label("fix_pool")
    asm.label("fix_pool_done")
    asm.lea_rip(RAX, "empty")
    asm.mov_mem_reg(RBP, EMPTY_P, RAX)
    asm.mov_mem_reg(RBP, REASON_P, RAX)
    asm.lea_rip(RAX, "prog")
    asm.mov_mem_reg(RBP, CODE, RAX)
    asm.lea_rip(RAX, "funcs")
    asm.mov_mem_reg(RBP, FUNCS, RAX)
    _kstack(asm)
    asm.mov_reg_imm32(RCX, 0xFFFFFFF5)
    asm.call_rip(_k(pe, "GetStdHandle"))
    asm.mov_mem_reg(RBP, STDOUT, RAX)
    _kstack(asm)
    asm.mov_reg_imm32(RCX, 0xFFFFFFF4)
    asm.call_rip(_k(pe, "GetStdHandle"))
    asm.mov_mem_reg(RBP, STDERR, RAX)
    _kstack(asm)
    asm.xor_reg(RCX, RCX)
    _i64(asm, RDX, HEAP_BYTES)
    asm.mov_reg_imm32(R8, 0x3000)
    asm.mov_reg_imm32(R9, 4)
    asm.call_rip(_k(pe, "VirtualAlloc"))
    asm.test_reg(RAX, RAX)
    asm.jz("oom")
    asm.mov_mem_reg(RBP, HEAP, RAX)
    asm.xor_reg(RCX, RCX)
    asm.mov_mem_reg(RBP, HEAP_USED, RCX)
    _i64(asm, RCX, HEAP_BYTES)
    asm.mov_mem_reg(RBP, HEAP_END, RCX)
    _kstack(asm)
    asm.xor_reg(RCX, RCX)
    _i64(asm, RDX, CELL_BYTES)
    asm.mov_reg_imm32(R8, 0x3000)
    asm.mov_reg_imm32(R9, 4)
    asm.call_rip(_k(pe, "VirtualAlloc"))
    asm.test_reg(RAX, RAX)
    asm.jz("oom")
    asm.mov_mem_reg(RBP, CELLS, RAX)
    _kstack(asm)
    asm.xor_reg(RCX, RCX)
    _i64(asm, RDX, CALL_BYTES)
    asm.mov_reg_imm32(R8, 0x3000)
    asm.mov_reg_imm32(R9, 4)
    asm.call_rip(_k(pe, "VirtualAlloc"))
    asm.test_reg(RAX, RAX)
    asm.jz("oom")
    asm.mov_mem_reg(RBP, CALLS, RAX)
    _argv(asm, pe)
    asm.xor_reg(RAX, RAX)
    asm.mov_mem_reg(RBP, FAILED, RAX)
    asm.mov_mem_reg(RBP, FRAME, RAX)
    asm.mov_mem_reg(RBP, DEPTH, RAX)
    asm.mov_mem_reg(RBP, CALL_I, RAX)
    asm.mov_mem_reg(RBP, REASON_N, RAX)
    _i64(asm, RAX, main.nlocals)
    asm.mov_mem_reg(RBP, SP, RAX)
    asm.mov_reg_mem(RDX, RBP, CODE)
    _i64(asm, RAX, main.off)
    asm.add_reg(RDX, RAX)
    asm.mov_mem_reg(RBP, IP, RDX)
    asm.jmp_label("dispatch")


def _argv(asm, pe: Image) -> None:
    _kstack(asm)
    asm.call_rip(_k(pe, "GetCommandLineW"))
    asm.mov_reg_reg(R12, RAX)
    asm.xor_reg(RAX, RAX)
    asm.mov_mem_reg(RBP, TEMP0, RAX)
    _kstack(asm)
    asm.mov_reg_reg(RCX, R12)
    asm.lea_rip(RDX, "header")
    asm.add_reg_imm8(RDX, TEMP0) if False else None
    # rdx = &header.TEMP0. TEMP0 fits in imm8? 208 does not. Use add with register.
    asm.lea_rip(RDX, "header")
    _i64(asm, RAX, TEMP0)
    asm.add_reg(RDX, RAX)
    asm.call_rip(_k(pe, "CommandLineToArgvW"))
    asm.test_reg(RAX, RAX)
    asm.jz("oom")
    asm.mov_reg_reg(R13, RAX)
    asm.movsxd_reg_mem(RAX, RBP, TEMP0)
    asm.mov_mem_reg(RBP, ARGC_AT, RAX)
    asm.mov_reg_reg(RCX, RAX)
    asm.shl_reg_imm8(RCX, 4)
    asm.call_label("alloc")
    asm.mov_mem_reg(RBP, ARGV, RAX)
    asm.mov_reg_reg(R14, RAX)
    asm.xor_reg(R15, R15)
    asm.label("arg_loop")
    asm.mov_reg_mem(RAX, RBP, ARGC_AT)
    asm.cmp_reg(R15, RAX)
    asm.jae("arg_done")
    asm.mov_reg_reg(RAX, R15)
    asm.shl_reg_imm8(RAX, 3)
    asm.add_reg(RAX, R13)
    asm.mov_reg_mem(R12, RAX, 0)
    _kstack(asm)
    asm.mov_reg_imm32(RCX, 65001)
    asm.xor_reg(RDX, RDX)
    asm.mov_reg_reg(R8, R12)
    asm.mov_reg_imm32(R9, 0xFFFFFFFF)
    asm.mov_rsp_imm32(0x20, 0)
    asm.mov_rsp_imm32(0x28, 0)
    asm.mov_rsp_imm32(0x30, 0)
    asm.mov_rsp_imm32(0x38, 0)
    asm.call_rip(_k(pe, "WideCharToMultiByte"))
    asm.raw(b"\x85\xC0")
    asm.jz("oom")
    asm.mov_reg_reg(RBX, RAX)
    asm.mov_reg_reg(RCX, RAX)
    asm.call_label("alloc")
    asm.mov_reg_reg(RSI, RAX)
    _kstack(asm)
    asm.mov_reg_imm32(RCX, 65001)
    asm.xor_reg(RDX, RDX)
    asm.mov_reg_reg(R8, R12)
    asm.mov_reg_imm32(R9, 0xFFFFFFFF)
    asm.mov_rsp_reg(0x20, RSI)
    asm.mov_rsp_reg(0x28, RBX)
    asm.mov_rsp_imm32(0x30, 0)
    asm.mov_rsp_imm32(0x38, 0)
    asm.call_rip(_k(pe, "WideCharToMultiByte"))
    asm.mov_reg_reg(RAX, RBX)
    asm.sub_reg_imm8(RAX, 1)
    asm.mov_mem_reg(R14, 0, RSI)
    asm.mov_mem_reg(R14, 8, RAX)
    asm.add_reg_imm8(R14, 16)
    asm.inc_reg(R15)
    asm.jmp_label("arg_loop")
    asm.label("arg_done")
    _kstack(asm)
    asm.mov_reg_reg(RCX, R13)
    asm.call_rip(_k(pe, "LocalFree"))


def _helpers(asm, pe: Image) -> None:
    asm.label("alloc")
    asm.test_reg(RCX, RCX)
    asm.jnz("alloc_nz")
    asm.mov_reg_imm32(RCX, 1)
    asm.label("alloc_nz")
    asm.add_reg_imm8(RCX, 7)
    asm.and_reg_imm8(RCX, -8)
    asm.mov_reg_mem(R8, RBP, HEAP_USED)
    asm.mov_reg_reg(RAX, R8)
    asm.add_reg(RAX, RCX)
    asm.jb("oom")
    asm.mov_reg_mem(RDX, RBP, HEAP_END)
    asm.cmp_reg(RAX, RDX)
    asm.ja("oom")
    asm.mov_mem_reg(RBP, HEAP_USED, RAX)
    asm.mov_reg_mem(RAX, RBP, HEAP)
    asm.add_reg(RAX, R8)
    asm.ret()
    asm.label("memcpy")
    asm.test_reg(R8, R8)
    asm.jz("memcpy_done")
    asm.label("memcpy_loop")
    asm.movzx_reg_byte_mem(RAX, RDX, 0)
    asm.mov_mem8_reg(RCX, 0, RAX)
    asm.inc_reg(RDX)
    asm.inc_reg(RCX)
    asm.dec_reg(R8)
    asm.jnz("memcpy_loop")
    asm.label("memcpy_done")
    asm.ret()
    asm.label("write_out")
    asm.test_reg(R8, R8)
    asm.jz("write_done")
    asm.mov_reg_reg(R12, RCX)
    asm.mov_reg_reg(R13, RDX)
    asm.mov_reg_reg(R14, R8)
    asm.label("write_loop")
    # Called with RSP ≡ 8 (mod 16). A private frame keeps the return address.
    # 0x28 is shadow space plus the fifth WriteFile argument, and 0x28 ≡ 8.
    asm.sub_rsp_imm32(0x28)
    asm.mov_reg_reg(RCX, R12)
    asm.mov_reg_reg(RDX, R13)
    asm.mov_reg_reg(R8, R14)
    asm.lea_rip(R9, "header")
    _i64(asm, RAX, TEMP0)
    asm.add_reg(R9, RAX)
    asm.mov_rsp_imm32(0x20, 0)
    asm.call_rip(_k(pe, "WriteFile"))
    asm.raw(b"\x85\xC0")
    asm.jz("write_unwind")
    asm.movsxd_reg_mem(RAX, RBP, TEMP0)
    asm.test_reg(RAX, RAX)
    asm.jz("write_unwind")
    asm.sub_reg(R14, RAX)
    asm.add_reg(R13, RAX)
    asm.add_rsp_imm32(0x28)
    asm.test_reg(R14, R14)
    asm.jnz("write_loop")
    asm.jmp_label("write_done")
    asm.label("write_unwind")
    asm.add_rsp_imm32(0x28)
    asm.label("write_done")
    asm.ret()
    asm.label("oom")
    _kstack(asm)
    asm.mov_reg_mem(RCX, RBP, STDERR)
    asm.lea_rip(RDX, "oom")
    asm.mov_reg_imm32(R8, len(b"out of memory\n"))
    asm.lea_rip(R9, "header")
    _i64(asm, RAX, TEMP0)
    asm.add_reg(R9, RAX)
    asm.mov_rsp_imm32(0x20, 0)
    asm.call_rip(_k(pe, "WriteFile"))
    _exit(asm, pe, 1)
    asm.label("dispatch")
    asm.mov_reg_mem(RSP, RBP, KSP)
    asm.mov_reg_mem(RAX, RBP, IP)
    asm.movzx_reg_byte_mem(RCX, RAX, 0)
    asm.inc_mem(RBP, IP)
    asm.mov_mem_reg(RBP, LASTOP, RCX)
    asm.cmp_reg_imm8(RCX, OPCOUNT)
    asm.jae("bad_op")
    asm.mov_reg_reg(RAX, RCX)
    asm.lea_rip(RDX, "optab")
    asm.jmp_sib(RDX, RAX)


def _ops(asm, pe: Image) -> None:
    _simple(asm, pe)
