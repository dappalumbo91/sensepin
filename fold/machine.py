def _simple(asm, pe: Image) -> None:
    asm.label("op_halt")
    _exit(asm, pe, 0)
    asm.label("op_write")
    _pop(asm)
    asm.mov_reg_mem(RCX, RBP, STDOUT)
    asm.mov_reg_mem(RDX, RBX, 8)
    asm.mov_reg_mem(R8, RBX, 16)
    asm.call_label("write_out")
    asm.jmp_label("dispatch")
    asm.label("op_fail")
    _pop(asm)
    asm.mov_reg_mem(R12, RBX, 8)
    asm.mov_reg_mem(R13, RBX, 16)
    asm.mov_reg_mem(RCX, RBP, STDERR)
    asm.mov_reg_reg(RDX, R12)
    asm.mov_reg_reg(R8, R13)
    asm.call_label("write_out")
    asm.mov_reg_mem(RCX, RBP, STDERR)
    asm.lea_rip(RDX, "nl")
    asm.mov_reg_imm32(R8, 1)
    asm.call_label("write_out")
    _exit(asm, pe, 1)
    asm.label("op_push_const")
    _read_u16(asm)
    asm.mov_reg_reg(R12, RCX)
    asm.shl_reg_imm8(R12, 5)
    asm.mov_reg_mem(RAX, RBP, POOL)
    asm.add_reg(R12, RAX)
    _slot(asm)
    for off in (0, 8, 16, 24):
        asm.mov_reg_mem(RAX, R12, off)
        asm.mov_mem_reg(RBX, off, RAX)
    asm.jmp_label("dispatch")
    asm.label("op_pop_local")
    _read_u16(asm)
    asm.mov_reg_reg(R12, RCX)
    _pop(asm)
    asm.mov_reg_reg(R13, RBX)
    asm.mov_reg_mem(RAX, RBP, FRAME)
    asm.add_reg(RAX, R12)
    asm.shl_reg_imm8(RAX, 5)
    asm.mov_reg_mem(R12, RBP, CELLS)
    asm.add_reg(R12, RAX)
    for off in (0, 8, 16, 24):
        asm.mov_reg_mem(RAX, R13, off)
        asm.mov_mem_reg(R12, off, RAX)
    asm.jmp_label("dispatch")
    asm.label("op_push_local")
    _read_u16(asm)
    asm.mov_reg_mem(RAX, RBP, FRAME)
    asm.add_reg(RAX, RCX)
    asm.shl_reg_imm8(RAX, 5)
    asm.mov_reg_mem(R12, RBP, CELLS)
    asm.add_reg(R12, RAX)
    _slot(asm)
    for off in (0, 8, 16, 24):
        asm.mov_reg_mem(RAX, R12, off)
        asm.mov_mem_reg(RBX, off, RAX)
    asm.jmp_label("dispatch")
    asm.label("op_clear")
    asm.xor_reg(RAX, RAX)
    asm.mov_mem_reg(RBP, FAILED, RAX)
    asm.jmp_label("dispatch")
    asm.label("op_reason")
    asm.mov_reg_mem(R12, RBP, REASON_P)
    asm.mov_reg_mem(R13, RBP, REASON_N)
    _push_bytes_tag(asm, TAG_BYTES)
    asm.jmp_label("dispatch")
    asm.label("op_argc")
    asm.mov_reg_mem(R12, RBP, ARGC_AT)
    _push_i64(asm)
    asm.jmp_label("dispatch")
    asm.label("op_arg")
    _pop(asm)
    asm.mov_reg_mem(RAX, RBX, 8)
    asm.test_reg(RAX, RAX)
    asm.jl("arg_fail")
    asm.mov_reg_mem(RCX, RBP, ARGC_AT)
    asm.cmp_reg(RAX, RCX)
    asm.jge("arg_fail")
    asm.shl_reg_imm8(RAX, 4)
    asm.mov_reg_mem(RDX, RBP, ARGV)
    asm.add_reg(RDX, RAX)
    asm.mov_reg_mem(R12, RDX, 0)
    asm.mov_reg_mem(R13, RDX, 8)
    _push_bytes_tag(asm, TAG_BYTES)
    asm.jmp_label("dispatch")
    asm.label("arg_fail")
    _fail_empty(asm)
    asm.jmp_label("dispatch")


def _arith(asm) -> None:
    def pop_ab(fail: str) -> None:
        _pop(asm)
        asm.mov_reg_mem(R12, RBX, 8)
        _pop(asm)
        asm.mov_reg_mem(RAX, RBX, 8)

    asm.label("op_add")
    pop_ab("add_fail")
    asm.add_reg(RAX, R12)
    asm.jo("add_fail")
    asm.mov_reg_reg(R12, RAX)
    _push_i64(asm)
    asm.jmp_label("dispatch")
    asm.label("add_fail")
    _fail_empty(asm)
    asm.jmp_label("dispatch")
    asm.label("op_sub")
    pop_ab("sub_fail")
    _i64(asm, RCX, I64_MIN)
    asm.cmp_reg(R12, RCX)
    asm.je("sub_fail")
    asm.neg_reg(R12)
    asm.add_reg(RAX, R12)
    asm.jo("sub_fail")
    asm.mov_reg_reg(R12, RAX)
    _push_i64(asm)
    asm.jmp_label("dispatch")
    asm.label("sub_fail")
    _fail_empty(asm)
    asm.jmp_label("dispatch")
    asm.label("op_mul")
    pop_ab("mul_fail")
    asm.imul_reg(RAX, R12)
    asm.jo("mul_fail")
    asm.mov_reg_reg(R12, RAX)
    _push_i64(asm)
    asm.jmp_label("dispatch")
    asm.label("mul_fail")
    _fail_empty(asm)
    asm.jmp_label("dispatch")
    asm.label("op_div")
    pop_ab("div_fail")
    asm.test_reg(R12, R12)
    asm.jz("div_fail")
    _i64(asm, RCX, I64_MIN)
    asm.cmp_reg(RAX, RCX)
    asm.jne("div_do")
    _i64(asm, RCX, -1)
    asm.cmp_reg(R12, RCX)
    asm.je("div_fail")
    asm.label("div_do")
    asm.cqo()
    asm.idiv_reg(R12)
    asm.mov_reg_reg(R12, RAX)
    _push_i64(asm)
    asm.jmp_label("dispatch")
    asm.label("div_fail")
    _fail_empty(asm)
    asm.jmp_label("dispatch")
    asm.label("op_neg")
    _pop(asm)
    asm.mov_reg_mem(RAX, RBX, 8)
    _i64(asm, RCX, I64_MIN)
    asm.cmp_reg(RAX, RCX)
    asm.je("neg_fail")
    asm.neg_reg(RAX)
    asm.mov_reg_reg(R12, RAX)
    _push_i64(asm)
    asm.jmp_label("dispatch")
    asm.label("neg_fail")
    _fail_empty(asm)
    asm.jmp_label("dispatch")
    asm.label("op_cmp")
    _read_u8(asm)
    asm.mov_reg_reg(R13, RCX)
    _pop(asm)
    asm.mov_reg_mem(R12, RBX, 8)
    _pop(asm)
    asm.mov_reg_mem(RAX, RBX, 8)
    asm.cmp_reg_imm8(R13, CMP_EQ)
    asm.je("cmp_eq")
    asm.cmp_reg_imm8(R13, CMP_NE)
    asm.je("cmp_ne")
    asm.cmp_reg_imm8(R13, CMP_LT)
    asm.je("cmp_lt")
    asm.cmp_reg_imm8(R13, CMP_GT)
    asm.je("cmp_gt")
    asm.cmp_reg_imm8(R13, CMP_LE)
    asm.je("cmp_le")
    asm.label("cmp_ge")
    asm.xor_reg(RCX, RCX)
    asm.cmp_reg(RAX, R12)
    asm.setcc(0x9D, RCX)
    asm.jmp_label("cmp_push")
    asm.label("cmp_eq")
    asm.xor_reg(RCX, RCX)
    asm.cmp_reg(RAX, R12)
    asm.setcc(0x94, RCX)
    asm.jmp_label("cmp_push")
    asm.label("cmp_ne")
    asm.xor_reg(RCX, RCX)
    asm.cmp_reg(RAX, R12)
    asm.setcc(0x95, RCX)
    asm.jmp_label("cmp_push")
    asm.label("cmp_lt")
    asm.xor_reg(RCX, RCX)
    asm.cmp_reg(RAX, R12)
    asm.setcc(0x9C, RCX)
    asm.jmp_label("cmp_push")
    asm.label("cmp_gt")
    asm.xor_reg(RCX, RCX)
    asm.cmp_reg(RAX, R12)
    asm.setcc(0x9F, RCX)
    asm.jmp_label("cmp_push")
    asm.label("cmp_le")
    asm.xor_reg(RCX, RCX)
    asm.cmp_reg(RAX, R12)
    asm.setcc(0x9E, RCX)
    asm.label("cmp_push")
    asm.mov_reg_reg(R12, RCX)
    _push_i64(asm)
    asm.jmp_label("dispatch")


def _flow(asm, pe: Image) -> None:
    asm.label("op_jump")
    _read_i32(asm)
    asm.add_mem_reg(RBP, IP, RCX)
    asm.jmp_label("dispatch")
    asm.label("op_jz")
    _pop(asm)
    asm.mov_reg_mem(RAX, RBX, 8)
    _read_i32(asm)
    asm.test_reg(RAX, RAX)
    asm.jnz("dispatch")
    asm.add_mem_reg(RBP, IP, RCX)
    asm.jmp_label("dispatch")
    asm.label("op_if_fail")
    _read_i32(asm)
    asm.mov_reg_mem(RAX, RBP, FAILED)
    asm.test_reg(RAX, RAX)
    asm.jz("dispatch")
    asm.add_mem_reg(RBP, IP, RCX)
    asm.jmp_label("dispatch")
    asm.label("op_dec")
    _pop(asm)
    asm.mov_reg_mem(RAX, RBX, 0)
    _i64(asm, RCX, TAG_F64)
    asm.cmp_reg(RAX, RCX)
    asm.jne("dec_i64")
    asm.mov_reg_mem(R12, RBX, 8)
    asm.jmp_label("dec_f64")
    asm.label("dec_i64")
    asm.mov_reg_mem(R12, RBX, 8)
    _i64(asm, RAX, I64_MIN)
    asm.cmp_reg(R12, RAX)
    asm.je("dec_min")
    asm.test_reg(R12, R12)
    asm.jnz("dec_nz")
    asm.lea_rip(R12, "chr0")
    _i64(asm, R13, 1)
    _push_bytes_tag(asm, TAG_BYTES)
    asm.jmp_label("dispatch")
    asm.label("dec_min")
    asm.lea_rip(R12, "mindec")
    _i64(asm, R13, 20)
    _push_bytes_tag(asm, TAG_BYTES)
    asm.jmp_label("dispatch")
    asm.label("dec_nz")
    asm.xor_reg(R15, R15)
    asm.test_reg(R12, R12)
    asm.jge("dec_pos")
    _i64(asm, R15, 1)
    asm.neg_reg(R12)
    asm.label("dec_pos")
    asm.lea_rip(R13, "header")
    _i64(asm, RAX, DIGIT + 32)
    asm.add_reg(R13, RAX)
    asm.xor_reg(R14, R14)
    asm.label("dec_loop")
    asm.xor_reg(RDX, RDX)
    asm.mov_reg_reg(RAX, R12)
    asm.mov_reg_imm32(RCX, 10)
    asm.udiv_reg(RCX)
    asm.add_reg_imm8(RDX, 48)
    asm.dec_reg(R13)
    asm.mov_mem8_reg(R13, 0, RDX)
    asm.inc_reg(R14)
    asm.mov_reg_reg(R12, RAX)
    asm.test_reg(RAX, RAX)
    asm.jnz("dec_loop")
    asm.test_reg(R15, R15)
    asm.jz("dec_copy")
    asm.dec_reg(R13)
    asm.mov_reg_imm32(RAX, ord("-"))
    asm.mov_mem8_reg(R13, 0, RAX)
    asm.inc_reg(R14)
    asm.label("dec_copy")
    asm.mov_reg_reg(RCX, R14)
    asm.call_label("alloc")
    asm.mov_mem_reg(RBP, TEMP1, RAX)
    asm.mov_reg_reg(RCX, RAX)
    asm.mov_reg_reg(RDX, R13)
    asm.mov_reg_reg(R8, R14)
    asm.call_label("memcpy")
    asm.mov_reg_mem(R12, RBP, TEMP1)
    asm.mov_reg_reg(R13, R14)
    _push_bytes_tag(asm, TAG_BYTES)
    asm.jmp_label("dispatch")
    asm.label("op_i64")
    _pop(asm)
    asm.mov_reg_mem(R12, RBX, 8)
    asm.mov_reg_mem(R13, RBX, 16)
    asm.test_reg(R13, R13)
    asm.jz("i64_fail")
    asm.xor_reg(R14, R14)
    asm.xor_reg(R15, R15)
    asm.xor_reg(RBX, RBX)
    asm.movzx_reg_byte_mem(RAX, R12, 0)
    asm.cmp_reg_imm8(RAX, ord("+"))
    asm.je("i64_sign")
    asm.cmp_reg_imm8(RAX, ord("-"))
    asm.jne("i64_digits")
    _i64(asm, R15, 1)
    asm.label("i64_sign")
    asm.inc_reg(R14)
    asm.cmp_reg(R14, R13)
    asm.jae("i64_fail")
    asm.label("i64_digits")
    asm.cmp_reg(R14, R13)
    asm.jae("i64_finish")
    asm.movzx_reg_byte_index(RAX, R12, R14)
    asm.cmp_reg_imm8(RAX, ord("0"))
    asm.jb("i64_fail")
    asm.cmp_reg_imm8(RAX, ord("9"))
    asm.ja("i64_fail")
    asm.sub_reg_imm8(RAX, ord("0"))
    asm.mov_reg_reg(R11, RAX)
    _i64(asm, RCX, (1 << 64) - 1)
    # UINT64_MAX // 10
    asm.mov_reg_imm64(RCX, 1844674407370955161) if False else _i64(asm, RCX, 1844674407370955161)
    asm.cmp_reg(RBX, RCX)
    asm.ja("i64_fail")
    asm.jne("i64_mul")
    asm.cmp_reg_imm8(R11, 5)
    asm.ja("i64_fail")
    asm.label("i64_mul")
    asm.imul_reg_imm8(RAX, RBX, 10)
    asm.add_reg(RAX, R11)
    asm.mov_reg_reg(RBX, RAX)
    asm.inc_reg(R14)
    asm.jmp_label("i64_digits")
    asm.label("i64_finish")
    asm.test_reg(R15, R15)
    asm.jnz("i64_neg")
    _i64(asm, RCX, I64_MAX)
    asm.cmp_reg(RBX, RCX)
    asm.ja("i64_fail")
    asm.mov_reg_reg(R12, RBX)
    _push_i64(asm)
    asm.jmp_label("dispatch")
    asm.label("i64_neg")
    _i64(asm, RCX, I64_MAX + 1)
    asm.cmp_reg(RBX, RCX)
    asm.ja("i64_fail")
    asm.jne("i64_neg_small")
    _i64(asm, R12, I64_MIN)
    _push_i64(asm)
    asm.jmp_label("dispatch")
    asm.label("i64_neg_small")
    asm.mov_reg_reg(R12, RBX)
    asm.neg_reg(R12)
    _push_i64(asm)
    asm.jmp_label("dispatch")
    asm.label("i64_fail")
    _fail_empty(asm)
    asm.jmp_label("dispatch")


def _bytes_ops(asm) -> None:
    asm.label("op_cat")
    _pop(asm)
    asm.mov_reg_mem(R12, RBX, 8)
    asm.mov_reg_mem(R13, RBX, 16)
    _pop(asm)
    asm.mov_reg_mem(R14, RBX, 8)
    asm.mov_reg_mem(R15, RBX, 16)
    # The heap never frees. Doubling the old capacity made a 192-byte pool ask
    # for 16MB on the sixth constant. Allocate the bytes this append needs.
    asm.mov_reg_reg(RCX, R13)
    asm.add_reg(RCX, R15)
    asm.jb("oom")
    asm.mov_mem_reg(RBP, TEMP4, RCX)
    asm.mov_mem_reg(RBP, TEMP6, RCX)
    asm.call_label("alloc")
    asm.mov_mem_reg(RBP, TEMP1, RAX)
    asm.test_reg(R15, R15)
    asm.jz("cat_b")
    asm.mov_reg_reg(RCX, RAX)
    asm.mov_reg_reg(RDX, R14)
    asm.mov_reg_reg(R8, R15)
    asm.call_label("memcpy")
    asm.label("cat_b")
    asm.test_reg(R13, R13)
    asm.jz("cat_push")
    asm.mov_reg_mem(RCX, RBP, TEMP1)
    asm.add_reg(RCX, R15)
    asm.mov_reg_reg(RDX, R12)
    asm.mov_reg_reg(R8, R13)
    asm.call_label("memcpy")
    asm.label("cat_push")
    asm.mov_reg_mem(R12, RBP, TEMP1)
    asm.mov_reg_mem(R13, RBP, TEMP4)
    _push_bytes_tag(asm, TAG_BYTES)
    asm.mov_reg_mem(RAX, RBP, TEMP6)
    asm.mov_mem_reg(RBX, 24, RAX)
    asm.jmp_label("dispatch")
    asm.label("op_make_byte")
    _pop(asm)
    asm.mov_reg_mem(R15, RBX, 8)
    asm.test_reg(R15, R15)
    asm.jl("byte_make_fail")
    asm.cmp_reg_imm32(R15, 255)
    asm.ja("byte_make_fail")
    asm.mov_reg_imm32(RCX, 1)
    asm.call_label("alloc")
    asm.mov_reg_reg(R12, RAX)
    asm.mov_reg_reg(RAX, R15)
    asm.mov_mem8_reg(R12, 0, RAX)
    asm.mov_reg_imm32(R13, 1)
    _push_bytes_tag(asm, TAG_BYTES)
    asm.mov_reg_imm32(RAX, 1)
    asm.mov_mem_reg(RBX, 24, RAX)
    asm.jmp_label("dispatch")
    asm.label("byte_make_fail")
    _fail_empty(asm)
    asm.jmp_label("dispatch")
    asm.label("op_set_byte")
    _pop(asm)
    asm.mov_reg_mem(R15, RBX, 8)
    _pop(asm)
    asm.mov_reg_mem(R14, RBX, 8)
    _pop(asm)
    asm.mov_reg_mem(R12, RBX, 8)
    asm.mov_reg_mem(R13, RBX, 16)
    asm.test_reg(R15, R15)
    asm.jl("set_byte_fail")
    asm.cmp_reg_imm32(R15, 255)
    asm.ja("set_byte_fail")
    asm.test_reg(R14, R14)
    asm.jl("set_byte_fail")
    asm.cmp_reg(R14, R13)
    asm.jae("set_byte_fail")
    asm.mov_mem_reg(RBP, TEMP1, R12)
    asm.mov_mem_reg(RBP, TEMP2, R13)
    asm.mov_mem_reg(RBP, TEMP3, R14)
    asm.mov_mem_reg(RBP, TEMP4, R15)
    asm.mov_reg_reg(RCX, R13)
    asm.call_label("alloc")
    asm.mov_mem_reg(RBP, TEMP5, RAX)
    asm.mov_reg_reg(RCX, RAX)
    asm.mov_reg_mem(RDX, RBP, TEMP1)
    asm.mov_reg_mem(R8, RBP, TEMP2)
    asm.call_label("memcpy")
    asm.mov_reg_mem(R12, RBP, TEMP5)
    asm.mov_reg_mem(RAX, RBP, TEMP3)
    asm.add_reg(R12, RAX)
    asm.mov_reg_mem(RAX, RBP, TEMP4)
    asm.mov_mem8_reg(R12, 0, RAX)
    asm.mov_reg_mem(R12, RBP, TEMP5)
    asm.mov_reg_mem(R13, RBP, TEMP2)
    _push_bytes_tag(asm, TAG_BYTES)
    asm.mov_reg_mem(RAX, RBP, TEMP2)
    asm.mov_mem_reg(RBX, 24, RAX)
    asm.jmp_label("dispatch")
    asm.label("set_byte_fail")
    _fail_empty(asm)
    asm.jmp_label("dispatch")
    asm.label("op_len")
    _pop(asm)
    asm.mov_reg_mem(R12, RBX, 16)
    _i64(asm, RCX, I64_MAX)
    asm.cmp_reg(R12, RCX)
    asm.ja("len_fail")
    _push_i64(asm)
    asm.jmp_label("dispatch")
    asm.label("len_fail")
    _fail_empty(asm)
    asm.jmp_label("dispatch")
    asm.label("op_byte")
    _pop(asm)
    asm.mov_reg_mem(R14, RBX, 8)
    _pop(asm)
    asm.mov_reg_mem(R12, RBX, 8)
    asm.mov_reg_mem(R13, RBX, 16)
    asm.test_reg(R14, R14)
    asm.jl("byte_fail")
    asm.cmp_reg(R14, R13)
    asm.jae("byte_fail")
    asm.movzx_reg_byte_index(RAX, R12, R14)
    asm.mov_reg_reg(R12, RAX)
    _push_i64(asm)
    asm.jmp_label("dispatch")
    asm.label("byte_fail")
    _fail_empty(asm)
    asm.jmp_label("dispatch")
    asm.label("op_line")
    _pop(asm)
    asm.mov_reg_mem(R15, RBX, 8)
    _pop(asm)
    asm.mov_reg_mem(R14, RBX, 8)
    _pop(asm)
    asm.mov_reg_mem(R12, RBX, 8)
    asm.mov_reg_mem(R13, RBX, 16)
    asm.mov_reg_reg(RAX, R14)
    asm.label("line_scan")
    asm.cmp_reg(RAX, R13)
    asm.jae("line_scanned")
    asm.movzx_reg_byte_index(RCX, R12, RAX)
    asm.cmp_reg_imm8(RCX, 10)
    asm.je("line_scanned")
    asm.inc_reg(RAX)
    asm.jmp_label("line_scan")
    asm.label("line_scanned")
    asm.mov_reg_reg(R8, RAX)
    asm.cmp_reg(R8, R14)
    asm.jbe("line_nostrip")
    asm.mov_reg_reg(RCX, R8)
    asm.dec_reg(RCX)
    asm.movzx_reg_byte_index(RDX, R12, RCX)
    asm.cmp_reg_imm8(RDX, 13)
    asm.jne("line_nostrip")
    asm.mov_reg_reg(R8, RCX)
    asm.label("line_nostrip")
    asm.mov_reg_reg(R10, R12)
    asm.add_reg(R10, R14)
    asm.mov_reg_reg(R11, R8)
    asm.sub_reg(R11, R14)
    asm.cmp_reg(RAX, R13)
    asm.jae("line_next_end")
    asm.mov_reg_reg(RBX, RAX)
    asm.inc_reg(RBX)
    asm.jmp_label("line_have")
    asm.label("line_next_end")
    asm.mov_reg_reg(RBX, R13)
    asm.label("line_have")
    asm.mov_mem_reg(RBP, TEMP1, R10)
    asm.mov_mem_reg(RBP, TEMP2, R11)
    asm.mov_mem_reg(RBP, TEMP3, RBX)
    asm.mov_reg_mem(R12, RBP, TEMP1)
    asm.mov_reg_mem(R13, RBP, TEMP2)
    _i64(asm, R14, TAG_LINE)
    _slot(asm)
    asm.mov_mem_reg(RBX, 0, R14)
    asm.mov_mem_reg(RBX, 8, R12)
    asm.mov_mem_reg(RBX, 16, R13)
    asm.mov_mem_reg(RBX, 24, R15)
    asm.mov_reg_mem(R12, RBP, TEMP3)
    _push_i64(asm)
    asm.jmp_label("dispatch")
    asm.label("op_field_n")
    _pop(asm)
    asm.mov_reg_mem(R12, RBX, 24)
    _push_i64(asm)
    asm.jmp_label("dispatch")
    asm.label("op_field_text")
    _pop(asm)
    asm.mov_reg_mem(R12, RBX, 8)
    asm.mov_reg_mem(R13, RBX, 16)
    _push_bytes_tag(asm, TAG_BYTES)
    asm.jmp_label("dispatch")
    _find_ops(asm)


def _find_ops(asm) -> None:
    asm.label("memeq")
    asm.test_reg(RCX, RCX)
    asm.jz("memeq_yes")
    asm.label("memeq_loop")
    asm.movzx_reg_byte_mem(RAX, R10, 0)
    asm.movzx_reg_byte_mem(RDX, R11, 0)
    asm.cmp_reg(RAX, RDX)
    asm.jne("memeq_no")
    asm.inc_reg(R10)
    asm.inc_reg(R11)
    asm.dec_reg(RCX)
    asm.jnz("memeq_loop")
    asm.label("memeq_yes")
    asm.mov_reg_imm32(RAX, 1)
    asm.ret()
    asm.label("memeq_no")
    asm.xor_reg(RAX, RAX)
    asm.ret()
    asm.label("op_before")
    _search(asm, "before")
    asm.label("op_after")
    _search(asm, "after")
    asm.label("op_holds")
    _pop(asm)
    asm.mov_reg_mem(R12, RBX, 8)
    asm.mov_reg_mem(R13, RBX, 16)
    _pop(asm)
    asm.mov_reg_mem(R14, RBX, 8)
    asm.mov_reg_mem(R15, RBX, 16)
    asm.test_reg(R13, R13)
    asm.jz("holds_fail")
    asm.xor_reg(RDI, RDI)
    asm.xor_reg(RBX, RBX)
    asm.label("holds_loop")
    asm.mov_reg_reg(RAX, R15)
    asm.sub_reg(RAX, RBX)
    asm.cmp_reg(R13, RAX)
    asm.ja("holds_done")
    asm.mov_reg_reg(R10, R14)
    asm.add_reg(R10, RBX)
    asm.mov_reg_reg(R11, R12)
    asm.mov_reg_reg(RCX, R13)
    asm.call_label("memeq")
    asm.cmp_reg_imm8(RAX, 1)
    asm.jne("holds_step")
    asm.inc_reg(RDI)
    asm.add_reg(RBX, R13)
    asm.jmp_label("holds_loop")
    asm.label("holds_step")
    asm.inc_reg(RBX)
    asm.jmp_label("holds_loop")
    asm.label("holds_done")
    asm.mov_reg_reg(R12, RDI)
    _push_i64(asm)
    asm.jmp_label("dispatch")
    asm.label("holds_fail")
    _fail_empty(asm)
    asm.jmp_label("dispatch")


def _search(asm, kind: str) -> None:
    hit = f"{kind}_hit"
    miss = f"{kind}_miss"
    loop = f"{kind}_loop"
    _pop(asm)
    asm.mov_reg_mem(R12, RBX, 8)
    asm.mov_reg_mem(R13, RBX, 16)
    _pop(asm)
    asm.mov_reg_mem(R14, RBX, 8)
    asm.mov_reg_mem(R15, RBX, 16)
    asm.test_reg(R13, R13)
    asm.jz(miss)
    asm.cmp_reg(R13, R15)
    asm.ja(miss)
    asm.xor_reg(RBX, RBX)
    asm.label(loop)
    asm.mov_reg_reg(RAX, R15)
    asm.sub_reg(RAX, R13)
    asm.cmp_reg(RBX, RAX)
    asm.ja(miss)
    asm.mov_reg_reg(R10, R14)
    asm.add_reg(R10, RBX)
    asm.mov_reg_reg(R11, R12)
    asm.mov_reg_reg(RCX, R13)
    asm.call_label("memeq")
    asm.cmp_reg_imm8(RAX, 1)
    asm.je(hit)
    asm.inc_reg(RBX)
    asm.jmp_label(loop)
    asm.label(hit)
    if kind == "before":
        asm.mov_reg_reg(R12, R14)
        asm.mov_reg_reg(R13, RBX)
    else:
        asm.mov_reg_reg(R12, R14)
        asm.add_reg(R12, RBX)
        asm.add_reg(R12, R13)
        asm.mov_reg_reg(RAX, R15)
        asm.sub_reg(RAX, RBX)
        asm.sub_reg(RAX, R13)
        asm.mov_reg_reg(R13, RAX)
    _push_bytes_tag(asm, TAG_BYTES)
    asm.jmp_label("dispatch")
    asm.label(miss)
    _fail_empty(asm)
    asm.jmp_label("dispatch")


def _open(asm, pe: Image) -> None:
    asm.label("op_open")
    _pop(asm)
    asm.mov_reg_mem(RAX, RBX, 8)
    asm.mov_mem_reg(RBP, TEMP7, RAX)
    asm.mov_reg_mem(RAX, RBX, 16)
    asm.mov_mem_reg(RBP, TEMP8, RAX)
    _pop(asm)
    asm.mov_reg_mem(RAX, RBX, 8)
    asm.mov_mem_reg(RBP, TEMP5, RAX)
    asm.mov_reg_mem(RAX, RBX, 16)
    asm.mov_mem_reg(RBP, TEMP6, RAX)
    _pop(asm)
    asm.mov_reg_mem(RAX, RBX, 8)
    asm.mov_mem_reg(RBP, TEMP3, RAX)
    asm.mov_reg_mem(RAX, RBX, 16)
    asm.mov_mem_reg(RBP, TEMP4, RAX)
    _pop(asm)
    asm.mov_reg_mem(RAX, RBX, 8)
    asm.mov_mem_reg(RBP, TEMP2, RAX)
    _pop(asm)
    asm.mov_reg_mem(R12, RBX, 8)
    asm.mov_reg_mem(R13, RBX, 16)
    asm.mov_mem_reg(RBP, 352, R12)
    asm.mov_mem_reg(RBP, 360, R13)
    asm.mov_reg_mem(RAX, RBP, TEMP2)
    asm.test_reg(RAX, RAX)
    asm.jl("open_large")
    asm.xor_reg(RBX, RBX)
    asm.label("open_nul")
    asm.cmp_reg(RBX, R13)
    asm.jae("open_term")
    asm.movzx_reg_byte_index(RAX, R12, RBX)
    asm.test_reg(RAX, RAX)
    asm.jz("open_missing")
    asm.inc_reg(RBX)
    asm.jmp_label("open_nul")
    asm.label("open_term")
    asm.mov_reg_reg(RCX, R13)
    asm.inc_reg(RCX)
    asm.call_label("alloc")
    asm.mov_reg_reg(R14, RAX)
    asm.mov_reg_reg(RCX, RAX)
    asm.mov_reg_reg(RDX, R12)
    asm.mov_reg_reg(R8, R13)
    asm.call_label("memcpy")
    asm.mov_reg_reg(RAX, R14)
    asm.add_reg(RAX, R13)
    asm.xor_reg(RCX, RCX)
    asm.mov_mem8_reg(RAX, 0, RCX)
    _kstack(asm)
    asm.mov_reg_reg(RCX, R14)
    asm.call_rip(_k(pe, "GetFileAttributesA"))
    # A 32-bit write zeros the high half, so INVALID_FILE_ATTRIBUTES is
    # 0x00000000FFFFFFFF and a sign-extended imm32 compare would miss it.
    asm.raw(b"\x89\xC0")
    asm.mov_reg_imm32(RCX, 0xFFFFFFFF)
    asm.cmp_reg(RAX, RCX)
    asm.je("open_missing")
    asm.mov_reg_reg(RCX, RAX)
    asm.and_reg_imm8(RCX, 0x10)
    asm.jnz("open_missing")
    _kstack(asm)
    asm.mov_reg_reg(RCX, R14)
    asm.mov_reg_imm32(RDX, 0x80000000)
    asm.mov_reg_imm32(R8, 1)
    asm.xor_reg(R9, R9)
    asm.mov_rsp_imm32(0x20, 3)
    asm.mov_rsp_imm32(0x28, 0x80)
    asm.mov_rsp_imm32(0x30, 0)
    asm.call_rip(_k(pe, "CreateFileA"))
    _i64(asm, RCX, -1)
    asm.cmp_reg(RAX, RCX)
    asm.je("open_missing")
    asm.mov_mem_reg(RBP, HANDLE, RAX)
    _kstack(asm)
    asm.mov_reg_reg(RCX, RAX)
    asm.lea_rip(RDX, "header")
    _i64(asm, R8, TEMP0)
    asm.add_reg(RDX, R8)
    asm.call_rip(_k(pe, "GetFileSizeEx"))
    asm.raw(b"\x85\xC0")
    asm.jz("open_close_missing")
    asm.mov_reg_mem(RAX, RBP, TEMP0)
    asm.test_reg(RAX, RAX)
    asm.jl("open_close_large")
    asm.jz("open_close_empty")
    asm.mov_reg_mem(RCX, RBP, TEMP2)
    asm.cmp_reg(RAX, RCX)
    asm.jg("open_close_large")
    asm.mov_reg_reg(R15, RAX)
    asm.mov_reg_reg(RCX, RAX)
    asm.call_label("alloc")
    asm.mov_reg_reg(R12, RAX)
    asm.xor_reg(R13, R13)
    asm.label("open_read")
    asm.cmp_reg(R13, R15)
    asm.jae("open_read_done")
    asm.mov_reg_reg(R8, R15)
    asm.sub_reg(R8, R13)
    _kstack(asm)
    asm.mov_reg_mem(RCX, RBP, HANDLE)
    asm.mov_reg_reg(RDX, R12)
    asm.add_reg(RDX, R13)
    asm.lea_rip(R9, "header")
    _i64(asm, RAX, TEMP1)
    asm.add_reg(R9, RAX)
    asm.mov_rsp_imm32(0x20, 0)
    asm.call_rip(_k(pe, "ReadFile"))
    asm.raw(b"\x85\xC0")
    asm.jz("open_close_missing")
    asm.mov_reg_mem(RAX, RBP, TEMP1)
    asm.test_reg(RAX, RAX)
    asm.jz("open_close_missing")
    asm.add_reg(R13, RAX)
    asm.jmp_label("open_read")
    asm.label("open_read_done")
    _kstack(asm)
    asm.mov_reg_mem(RCX, RBP, HANDLE)
    asm.call_rip(_k(pe, "CloseHandle"))
    asm.mov_reg_reg(R13, R15)
    _push_bytes_tag(asm, TAG_BYTES)
    asm.jmp_label("dispatch")
    asm.label("open_close_missing")
    _close(asm, pe)
    asm.jmp_label("open_missing")
    asm.label("open_close_empty")
    _close(asm, pe)
    asm.jmp_label("open_empty")
    asm.label("open_close_large")
    _close(asm, pe)
    asm.jmp_label("open_large")
    asm.label("open_missing")
    _cat_reason(asm, TEMP3, TEMP4)
    asm.jmp_label("dispatch")
    asm.label("open_empty")
    asm.mov_reg_mem(R12, RBP, TEMP5)
    asm.mov_reg_mem(R13, RBP, TEMP6)
    _fail_r12(asm)
    asm.jmp_label("dispatch")
    asm.label("open_large")
    asm.mov_reg_mem(R12, RBP, TEMP7)
    asm.mov_reg_mem(R13, RBP, TEMP8)
    _fail_r12(asm)
    asm.jmp_label("dispatch")


def _close(asm, pe: Image) -> None:
    _kstack(asm)
    asm.mov_reg_mem(RCX, RBP, HANDLE)
    asm.call_rip(_k(pe, "CloseHandle"))


def _cat_reason(asm, ptr_at: int, len_at: int) -> None:
    # cat reason prefix at ptr_at with path in the saved path cell. Path ptr was overwritten.
    # The original path pointer is not saved. Re-read is impossible.
    # Caller must have left the path in r12/r13 only on the nul/attr path.
    # For close paths, path is still in the terminated buffer, but the message wants the original bytes.
    # Save path at the start: TEMP is used. Store path in unused spots? HANDLE is the handle.
    # Use RETBUF area: we stored path in r12 at the beginning and never saved it for the close path.
    # Fix by saving path into header bytes 352 and 360 at the start of open. Done in _open? 
    # This helper expects path ptr/len already in R14/R15? We'll set that contract in the caller.
    asm.mov_reg_mem(R14, RBP, ptr_at)
    asm.mov_reg_mem(R15, RBP, len_at)
    # path must be in TEMP9-like. We will store it at 352/360 from _open. Use DIGIT-adjacent 352.
    asm.mov_reg_mem(R12, RBP, 352)
    asm.mov_reg_mem(R13, RBP, 360)
    asm.mov_reg_reg(RCX, R15)
    asm.add_reg(RCX, R13)
    asm.jb("oom")
    asm.call_label("alloc")
    asm.mov_mem_reg(RBP, TEMP1, RAX)
    asm.test_reg(R15, R15)
    asm.jz("cat_reason_b")
    asm.mov_reg_reg(RCX, RAX)
    asm.mov_reg_reg(RDX, R14)
    asm.mov_reg_reg(R8, R15)
    asm.call_label("memcpy")
    asm.label("cat_reason_b")
    asm.test_reg(R13, R13)
    asm.jz("cat_reason_push")
    asm.mov_reg_mem(RCX, RBP, TEMP1)
    asm.add_reg(RCX, R15)
    asm.mov_reg_reg(RDX, R12)
    asm.mov_reg_reg(R8, R13)
    asm.call_label("memcpy")
    asm.label("cat_reason_push")
    asm.mov_reg_mem(R12, RBP, TEMP1)
    asm.mov_reg_reg(RAX, R15)
    asm.add_reg(RAX, R13)
    asm.mov_reg_reg(R13, RAX)
    _fail_r12(asm)


def _save_op(asm, pe: Image) -> None:
    asm.label("op_save")
    _pop(asm)
    asm.mov_reg_mem(R12, RBX, 8)
    asm.mov_reg_mem(R13, RBX, 16)
    asm.mov_mem_reg(RBP, TEMP1, R12)
    asm.mov_mem_reg(RBP, TEMP2, R13)
    _pop(asm)
    asm.mov_reg_mem(R14, RBX, 8)
    asm.mov_reg_mem(R15, RBX, 16)
    asm.xor_reg(RBX, RBX)
    asm.label("save_nul")
    asm.cmp_reg(RBX, R15)
    asm.jae("save_term")
    asm.movzx_reg_byte_index(RAX, R14, RBX)
    asm.test_reg(RAX, RAX)
    asm.jz("save_fail")
    asm.inc_reg(RBX)
    asm.jmp_label("save_nul")
    asm.label("save_term")
    asm.mov_reg_reg(RCX, R15)
    asm.inc_reg(RCX)
    asm.call_label("alloc")
    asm.mov_mem_reg(RBP, TEMP3, RAX)
    asm.mov_reg_reg(RCX, RAX)
    asm.mov_reg_reg(RDX, R14)
    asm.mov_reg_reg(R8, R15)
    asm.call_label("memcpy")
    asm.mov_reg_mem(RAX, RBP, TEMP3)
    asm.add_reg(RAX, R15)
    asm.xor_reg(RCX, RCX)
    asm.mov_mem8_reg(RAX, 0, RCX)
    _kstack(asm)
    asm.mov_reg_mem(RCX, RBP, TEMP3)
    asm.mov_reg_imm32(RDX, 0x40000000)
    asm.xor_reg(R8, R8)
    asm.xor_reg(R9, R9)
    asm.mov_rsp_imm32(0x20, 2)
    asm.mov_rsp_imm32(0x28, 0x80)
    asm.mov_rsp_imm32(0x30, 0)
    asm.call_rip(_k(pe, "CreateFileA"))
    _i64(asm, RCX, -1)
    asm.cmp_reg(RAX, RCX)
    asm.je("save_fail")
    asm.mov_mem_reg(RBP, HANDLE, RAX)
    asm.mov_reg_reg(RCX, RAX)
    asm.mov_reg_mem(RDX, RBP, TEMP1)
    asm.mov_reg_mem(R8, RBP, TEMP2)
    asm.call_label("write_out")
    _kstack(asm)
    asm.mov_reg_mem(RCX, RBP, HANDLE)
    asm.call_rip(_k(pe, "CloseHandle"))
    asm.mov_reg_mem(R12, RBP, TEMP2)
    _push_i64(asm)
    asm.jmp_label("dispatch")
    asm.label("save_fail")
    _fail_empty(asm)
    asm.jmp_label("dispatch")


def _call_ops(asm, pe: Image) -> None:
    asm.label("op_call")
    _read_u16(asm)
    asm.mov_reg_reg(RAX, RCX)
    asm.imul_reg_imm8(RAX, RAX, 24)
    asm.mov_reg_mem(RDX, RBP, FUNCS)
    asm.add_reg(RDX, RAX)
    asm.mov_reg_mem(R13, RDX, 0)
    asm.mov_reg_mem(R14, RDX, 8)
    asm.mov_reg_mem(R15, RDX, 16)
    asm.mov_reg_mem(RAX, RBP, DEPTH)
    asm.cmp_reg_imm32(RAX, CALL_CAP) if False else asm.cmp_reg_imm32(RAX, CALL_CAP)
    asm.jae("op_depth")
    asm.mov_reg_mem(RAX, RBP, SP)
    asm.sub_reg(RAX, R14)
    asm.mov_reg_reg(RBX, RAX)
    asm.mov_reg_mem(RAX, RBP, CALL_I)
    asm.imul_reg_imm8(RAX, RAX, 24)
    asm.mov_reg_mem(RDX, RBP, CALLS)
    asm.add_reg(RDX, RAX)
    asm.mov_reg_mem(RAX, RBP, IP)
    asm.mov_mem_reg(RDX, 0, RAX)
    asm.mov_reg_mem(RAX, RBP, FRAME)
    asm.mov_mem_reg(RDX, 8, RAX)
    asm.mov_mem_reg(RDX, 16, RBX)
    asm.inc_mem(RBP, CALL_I)
    asm.mov_reg_reg(R12, R14)
    asm.label("call_zero")
    asm.cmp_reg(R12, R15)
    asm.jae("call_zero_done")
    asm.mov_reg_reg(RAX, RBX)
    asm.add_reg(RAX, R12)
    asm.shl_reg_imm8(RAX, 5)
    asm.mov_reg_mem(RDX, RBP, CELLS)
    asm.add_reg(RDX, RAX)
    asm.xor_reg(RAX, RAX)
    asm.mov_mem_reg(RDX, 0, RAX)
    asm.mov_mem_reg(RDX, 8, RAX)
    asm.mov_mem_reg(RDX, 16, RAX)
    asm.mov_mem_reg(RDX, 24, RAX)
    asm.inc_reg(R12)
    asm.jmp_label("call_zero")
    asm.label("call_zero_done")
    asm.mov_reg_reg(RAX, RBX)
    asm.add_reg(RAX, R15)
    asm.mov_mem_reg(RBP, SP, RAX)
    asm.mov_mem_reg(RBP, FRAME, RBX)
    asm.mov_reg_mem(RAX, RBP, CODE)
    asm.add_reg(RAX, R13)
    asm.mov_mem_reg(RBP, IP, RAX)
    asm.inc_mem(RBP, DEPTH)
    asm.jmp_label("dispatch")
    asm.label("op_depth")
    _kstack(asm)
    asm.mov_reg_mem(RCX, RBP, STDERR)
    asm.lea_rip(RDX, "depthmsg")
    asm.mov_reg_imm32(R8, len(b"call depth\n"))
    asm.lea_rip(R9, "header")
    _i64(asm, RAX, TEMP0)
    asm.add_reg(R9, RAX)
    asm.mov_rsp_imm32(0x20, 0)
    asm.call_rip(_k(pe, "WriteFile"))
    _exit(asm, pe, 1)
    asm.label("op_ret")
    _pop(asm)
    for off in (0, 8, 16, 24):
        asm.mov_reg_mem(RAX, RBX, off)
        asm.mov_mem_reg(RBP, RETBUF + off, RAX)
    _restore(asm)
    _slot(asm)
    for off in (0, 8, 16, 24):
        asm.mov_reg_mem(RAX, RBP, RETBUF + off)
        asm.mov_mem_reg(RBX, off, RAX)
    asm.jmp_label("dispatch")
    asm.label("op_ret_fail")
    _pop(asm)
    asm.mov_reg_mem(R12, RBX, 8)
    asm.mov_reg_mem(R13, RBX, 16)
    _fail_r12(asm)
    _restore(asm)
    asm.jmp_label("dispatch")


def _restore(asm) -> None:
    asm.dec_mem(RBP, CALL_I)
    asm.dec_mem(RBP, DEPTH)
    asm.mov_reg_mem(RAX, RBP, CALL_I)
    asm.imul_reg_imm8(RAX, RAX, 24)
    asm.mov_reg_mem(RDX, RBP, CALLS)
    asm.add_reg(RDX, RAX)
    asm.mov_reg_mem(RAX, RDX, 0)
    asm.mov_mem_reg(RBP, IP, RAX)
    asm.mov_reg_mem(RAX, RDX, 8)
    asm.mov_mem_reg(RBP, FRAME, RAX)
    asm.mov_reg_mem(RAX, RDX, 16)
    asm.mov_mem_reg(RBP, SP, RAX)


def _value_ops(asm) -> None:
    def fbin(name: str, op) -> None:
        asm.label(name)
        _pop(asm)
        asm.mov_reg_mem(R13, RBX, 8)
        _pop(asm)
        asm.mov_reg_mem(R12, RBX, 8)
        asm.movq_xmm_reg(0, R12)
        asm.movq_xmm_reg(1, R13)
        op(0, 1)
        asm.jmp_label("f64_finish")

    fbin("op_fadd", asm.addsd)
    fbin("op_fsub", asm.subsd)
    fbin("op_fmul", asm.mulsd)
    fbin("op_fdiv", asm.divsd)
    asm.label("op_fneg")
    _pop(asm)
    asm.mov_reg_mem(R12, RBX, 8)
    _i64(asm, RCX, 1 << 63)
    asm.xor_reg(R12, RCX)
    asm.movq_xmm_reg(0, R12)
    asm.jmp_label("f64_finish")
    asm.label("f64_finish")
    asm.movq_reg_xmm(R12, 0)
    asm.mov_reg_reg(RAX, R12)
    _i64(asm, RCX, 0x7FF0000000000000)
    asm.and_reg(RAX, RCX)
    asm.cmp_reg(RAX, RCX)
    asm.je("f64_fail")
    asm.xor_reg(R13, R13)
    _push_bytes_tag(asm, TAG_F64)
    asm.jmp_label("dispatch")
    asm.label("f64_fail")
    _fail_empty(asm)
    asm.jmp_label("dispatch")
    asm.label("op_fcmp")
    _read_u8(asm)
    asm.mov_reg_reg(R15, RCX)
    _pop(asm)
    asm.mov_reg_mem(R13, RBX, 8)
    _pop(asm)
    asm.mov_reg_mem(R12, RBX, 8)
    asm.movq_xmm_reg(0, R12)
    asm.movq_xmm_reg(1, R13)
    asm.ucomisd(0, 1)
    asm.jcc(0x0A, "fcmp_nan")
    kinds = (
        (CMP_EQ, 0x94, "fcmp_eq"),
        (CMP_NE, 0x95, "fcmp_ne"),
        (CMP_LT, 0x92, "fcmp_lt"),
        (CMP_GT, 0x97, "fcmp_gt"),
        (CMP_LE, 0x96, "fcmp_le"),
    )
    for kind, _cc, name in kinds:
        asm.cmp_reg_imm8(R15, kind)
        asm.je(name)
    asm.label("fcmp_ge")
    asm.xor_reg(RCX, RCX)
    asm.ucomisd(0, 1)
    asm.setcc(0x93, RCX)
    asm.jmp_label("fcmp_push")
    for _kind, cc, name in kinds:
        asm.label(name)
        asm.xor_reg(RCX, RCX)
        asm.ucomisd(0, 1)
        asm.setcc(cc, RCX)
        asm.jmp_label("fcmp_push")
    asm.label("fcmp_nan")
    asm.xor_reg(RCX, RCX)
    asm.cmp_reg_imm8(R15, CMP_NE)
    asm.jne("fcmp_push")
    asm.mov_reg_imm32(RCX, 1)
    asm.label("fcmp_push")
    asm.mov_reg_reg(R12, RCX)
    _push_i64(asm)
    asm.jmp_label("dispatch")
    asm.label("op_ffrom")
    _pop(asm)
    asm.mov_reg_mem(RAX, RBX, 8)
    asm.cvtsi2sd(0, RAX)
    asm.movq_reg_xmm(R12, 0)
    asm.xor_reg(R13, R13)
    _push_bytes_tag(asm, TAG_F64)
    asm.jmp_label("dispatch")
    asm.label("op_ftoi")
    _pop(asm)
    asm.mov_reg_mem(R12, RBX, 8)
    asm.mov_reg_reg(RAX, R12)
    _i64(asm, RCX, 0x7FF0000000000000)
    asm.and_reg(RAX, RCX)
    asm.cmp_reg(RAX, RCX)
    asm.je("f64_fail")
    asm.movq_xmm_reg(0, R12)
    _i64(asm, RAX, 0x43E0000000000000)
    asm.movq_xmm_reg(1, RAX)
    asm.ucomisd(0, 1)
    asm.jae("f64_fail")
    _i64(asm, RAX, 0xC3E0000000000000)
    asm.movq_xmm_reg(1, RAX)
    asm.ucomisd(0, 1)
    asm.jb("f64_fail")
    asm.cvttsd2si(R12, 0)
    _push_i64(asm)
    asm.jmp_label("dispatch")
    asm.label("op_list_new")
    _i64(asm, R14, TAG_LIST)
    asm.jmp_label("agg_new")
    asm.label("op_struct_new")
    _i64(asm, R14, TAG_STRUCT)
    asm.label("agg_new")
    _read_u16(asm)
    asm.mov_reg_reg(R13, RCX)
    asm.test_reg(R13, R13)
    asm.jz("agg_empty")
    asm.mov_reg_reg(RCX, R13)
    asm.shl_reg_imm8(RCX, 5)
    asm.call_label("alloc")
    asm.mov_mem_reg(RBP, TEMP1, RAX)
    asm.mov_reg_mem(RAX, RBP, SP)
    asm.sub_reg(RAX, R13)
    asm.shl_reg_imm8(RAX, 5)
    asm.mov_reg_mem(RDX, RBP, CELLS)
    asm.add_reg(RDX, RAX)
    asm.mov_mem_reg(RBP, TEMP2, RDX)
    asm.mov_reg_mem(RCX, RBP, TEMP1)
    asm.mov_reg_mem(RDX, RBP, TEMP2)
    asm.mov_reg_reg(R8, R13)
    asm.shl_reg_imm8(R8, 5)
    asm.call_label("memcpy")
    asm.mov_reg_mem(RAX, RBP, SP)
    asm.sub_reg(RAX, R13)
    asm.mov_mem_reg(RBP, SP, RAX)
    asm.mov_reg_mem(R12, RBP, TEMP1)
    _push_bytes(asm)
    asm.jmp_label("dispatch")
    asm.label("agg_empty")
    asm.xor_reg(R12, R12)
    asm.xor_reg(R13, R13)
    _push_bytes(asm)
    asm.jmp_label("dispatch")
    asm.label("op_list_push")
    _pop(asm)
    for off in (0, 8, 16, 24):
        asm.mov_reg_mem(RAX, RBX, off)
        asm.mov_mem_reg(RBP, RETBUF + off, RAX)
    _pop(asm)
    asm.mov_reg_mem(R12, RBX, 8)
    asm.mov_reg_mem(R13, RBX, 16)
    asm.mov_mem_reg(RBP, TEMP1, R12)
    asm.mov_mem_reg(RBP, TEMP2, R13)
    asm.mov_reg_reg(RCX, R13)
    asm.inc_reg(RCX)
    asm.shl_reg_imm8(RCX, 5)
    asm.call_label("alloc")
    asm.mov_mem_reg(RBP, TEMP3, RAX)
    asm.mov_reg_reg(RCX, RAX)
    asm.mov_reg_mem(RDX, RBP, TEMP1)
    asm.mov_reg_mem(R8, RBP, TEMP2)
    asm.shl_reg_imm8(R8, 5)
    asm.call_label("memcpy")
    asm.mov_reg_mem(RCX, RBP, TEMP3)
    asm.mov_reg_mem(RAX, RBP, TEMP2)
    asm.shl_reg_imm8(RAX, 5)
    asm.add_reg(RCX, RAX)
    asm.mov_reg_reg(RDX, RBP)
    _i64(asm, RAX, RETBUF)
    asm.add_reg(RDX, RAX)
    asm.mov_reg_imm32(R8, 32)
    asm.call_label("memcpy")
    asm.mov_reg_mem(R12, RBP, TEMP3)
    asm.mov_reg_mem(R13, RBP, TEMP2)
    asm.inc_reg(R13)
    _push_bytes_tag(asm, TAG_LIST)
    asm.jmp_label("dispatch")
    asm.label("op_list_at")
    _pop(asm)
    asm.mov_reg_mem(R13, RBX, 8)
    _pop(asm)
    asm.mov_reg_mem(R12, RBX, 8)
    asm.mov_reg_mem(R14, RBX, 16)
    asm.test_reg(R13, R13)
    asm.jl("at_fail")
    asm.cmp_reg(R13, R14)
    asm.jae("at_fail")
    asm.shl_reg_imm8(R13, 5)
    asm.add_reg(R12, R13)
    _slot(asm)
    asm.mov_reg_reg(RCX, RBX)
    asm.mov_reg_reg(RDX, R12)
    asm.mov_reg_imm32(R8, 32)
    asm.call_label("memcpy")
    asm.jmp_label("dispatch")
    asm.label("at_fail")
    _fail_empty(asm)
    asm.jmp_label("dispatch")
    asm.label("op_list_len")
    _pop(asm)
    asm.mov_reg_mem(R12, RBX, 16)
    _i64(asm, RCX, I64_MAX)
    asm.cmp_reg(R12, RCX)
    asm.ja("list_len_fail")
    _push_i64(asm)
    asm.jmp_label("dispatch")
    asm.label("list_len_fail")
    _fail_empty(asm)
    asm.jmp_label("dispatch")
    asm.label("op_field")
    _read_u16(asm)
    asm.mov_reg_reg(R13, RCX)
    _pop(asm)
    asm.mov_reg_mem(R12, RBX, 8)
    asm.shl_reg_imm8(R13, 5)
    asm.add_reg(R12, R13)
    _slot(asm)
    asm.mov_reg_reg(RCX, RBX)
    asm.mov_reg_reg(RDX, R12)
    asm.mov_reg_imm32(R8, 32)
    asm.call_label("memcpy")
    asm.jmp_label("dispatch")


def _map_ops(asm) -> None:
    # Map entries are 64 bytes: key cell, then value cell. put copies the
    # 32-byte cells and leaves nested storage shared. MAP_BASE, MAP_PAIR, and
    # MAP_TOTAL belong to MAP_NEW across the put call.
    asm.label("map_key_eq")
    asm.mov_reg_mem(RAX, R10, 0)
    asm.mov_reg_mem(RCX, R11, 0)
    asm.cmp_reg(RAX, RCX)
    asm.jne("map_key_no")
    asm.cmp_reg_imm8(RAX, TAG_F64)
    asm.je("map_key_f64")
    asm.cmp_reg_imm8(RAX, TAG_BYTES)
    asm.je("map_key_bytes")
    asm.mov_reg_mem(RAX, R10, 8)
    asm.mov_reg_mem(RDX, R11, 8)
    asm.xor_reg(RCX, RCX)
    asm.cmp_reg(RAX, RDX)
    asm.setcc(0x94, RCX)
    asm.mov_reg_reg(RAX, RCX)
    asm.ret()
    asm.label("map_key_f64")
    asm.mov_reg_mem(RAX, R10, 8)
    asm.mov_reg_mem(RDX, R11, 8)
    asm.movq_xmm_reg(0, RAX)
    asm.movq_xmm_reg(1, RDX)
    asm.xor_reg(RAX, RAX)
    asm.ucomisd(0, 1)
    # NaN sets ZF, so SETE would say equal unless the unordered case leaves first.
    asm.jcc(0x0A, "map_key_no")
    asm.setcc(0x94, RAX)
    asm.ret()
    asm.label("map_key_bytes")
    asm.mov_reg_mem(RAX, R10, 16)
    asm.mov_reg_mem(RCX, R11, 16)
    asm.cmp_reg(RAX, RCX)
    asm.jne("map_key_no")
    asm.mov_reg_mem(RDX, R10, 8)
    asm.mov_reg_mem(R8, R11, 8)
    asm.mov_reg_reg(R10, RDX)
    asm.mov_reg_reg(R11, R8)
    asm.call_label("memeq")
    asm.ret()
    asm.label("map_key_no")
    asm.xor_reg(RAX, RAX)
    asm.ret()
    asm.label("map_find")
    asm.mov_mem_reg(RBP, MAP_PTR, R12)
    asm.mov_mem_reg(RBP, MAP_N, R13)
    asm.mov_mem_reg(RBP, KEY_AT, R14)
    asm.xor_reg(RBX, RBX)
    asm.label("map_find_loop")
    asm.mov_reg_mem(RAX, RBP, MAP_N)
    asm.cmp_reg(RBX, RAX)
    asm.jae("map_find_miss")
    asm.mov_reg_mem(R10, RBP, MAP_PTR)
    asm.mov_reg_reg(RAX, RBX)
    asm.shl_reg_imm8(RAX, 6)
    asm.add_reg(R10, RAX)
    asm.mov_reg_mem(R11, RBP, KEY_AT)
    asm.call_label("map_key_eq")
    asm.cmp_reg_imm8(RAX, 1)
    asm.je("map_find_hit")
    asm.inc_reg(RBX)
    asm.jmp_label("map_find_loop")
    asm.label("map_find_hit")
    asm.mov_reg_reg(RAX, RBX)
    asm.ret()
    asm.label("map_find_miss")
    asm.xor_reg(RAX, RAX)
    asm.dec_reg(RAX)
    asm.ret()
    asm.label("map_put")
    asm.mov_mem_reg(RBP, MAP_PTR, R12)
    asm.mov_mem_reg(RBP, MAP_N, R13)
    asm.mov_mem_reg(RBP, KEY_AT, R14)
    asm.mov_mem_reg(RBP, MAP_VAL, R15)
    asm.call_label("map_find")
    asm.mov_mem_reg(RBP, MAP_FOUND, RAX)
    asm.mov_reg_mem(R13, RBP, MAP_N)
    asm.test_reg(RAX, RAX)
    asm.jcc(0x09, "map_put_sized")
    asm.inc_reg(R13)
    asm.label("map_put_sized")
    asm.mov_reg_reg(RCX, R13)
    asm.shl_reg_imm8(RCX, 6)
    asm.call_label("alloc")
    asm.mov_reg_reg(R12, RAX)
    asm.mov_reg_reg(RCX, R12)
    asm.mov_reg_mem(RDX, RBP, MAP_PTR)
    asm.mov_reg_mem(R8, RBP, MAP_N)
    asm.shl_reg_imm8(R8, 6)
    asm.call_label("memcpy")
    asm.mov_reg_mem(RAX, RBP, MAP_FOUND)
    asm.test_reg(RAX, RAX)
    asm.jcc(0x08, "map_put_append")
    asm.mov_reg_reg(RCX, R12)
    asm.shl_reg_imm8(RAX, 6)
    asm.add_reg(RCX, RAX)
    asm.add_reg_imm8(RCX, 32)
    asm.mov_reg_mem(RDX, RBP, MAP_VAL)
    asm.mov_reg_imm32(R8, 32)
    asm.call_label("memcpy")
    asm.jmp_label("map_put_done")
    asm.label("map_put_append")
    asm.mov_reg_reg(RCX, R12)
    asm.mov_reg_mem(RAX, RBP, MAP_N)
    asm.shl_reg_imm8(RAX, 6)
    asm.add_reg(RCX, RAX)
    asm.mov_reg_mem(RDX, RBP, KEY_AT)
    asm.mov_reg_imm32(R8, 32)
    asm.call_label("memcpy")
    asm.mov_reg_reg(RCX, R12)
    asm.mov_reg_mem(RAX, RBP, MAP_N)
    asm.shl_reg_imm8(RAX, 6)
    asm.add_reg(RCX, RAX)
    asm.add_reg_imm8(RCX, 32)
    asm.mov_reg_mem(RDX, RBP, MAP_VAL)
    asm.mov_reg_imm32(R8, 32)
    asm.call_label("memcpy")
    asm.label("map_put_done")
    asm.ret()
    asm.label("op_map_new")
    _read_u16(asm)
    asm.test_reg(RCX, RCX)
    asm.jz("map_new_empty")
    asm.mov_mem_reg(RBP, MAP_TOTAL, RCX)
    asm.mov_reg_mem(RAX, RBP, SP)
    asm.shl_reg_imm8(RCX, 1)
    asm.sub_reg(RAX, RCX)
    asm.mov_mem_reg(RBP, MAP_BASE, RAX)
    asm.xor_reg(RAX, RAX)
    asm.mov_mem_reg(RBP, MAP_PAIR, RAX)
    asm.xor_reg(R12, R12)
    asm.xor_reg(R13, R13)
    asm.label("map_new_loop")
    asm.mov_reg_mem(RAX, RBP, MAP_PAIR)
    asm.mov_reg_mem(RCX, RBP, MAP_TOTAL)
    asm.cmp_reg(RAX, RCX)
    asm.jae("map_new_finish")
    asm.mov_reg_reg(RCX, RAX)
    asm.shl_reg_imm8(RCX, 1)
    asm.mov_reg_mem(RDX, RBP, MAP_BASE)
    asm.add_reg(RCX, RDX)
    asm.shl_reg_imm8(RCX, 5)
    asm.mov_reg_mem(RDX, RBP, CELLS)
    asm.add_reg(RDX, RCX)
    asm.mov_reg_reg(R14, RDX)
    asm.mov_reg_reg(R15, RDX)
    asm.add_reg_imm8(R15, 32)
    asm.call_label("map_put")
    asm.mov_reg_mem(RAX, RBP, MAP_PAIR)
    asm.inc_reg(RAX)
    asm.mov_mem_reg(RBP, MAP_PAIR, RAX)
    asm.jmp_label("map_new_loop")
    asm.label("map_new_finish")
    asm.mov_reg_mem(RAX, RBP, MAP_BASE)
    asm.mov_mem_reg(RBP, SP, RAX)
    _push_bytes_tag(asm, TAG_MAP)
    asm.jmp_label("dispatch")
    asm.label("map_new_empty")
    asm.xor_reg(R12, R12)
    asm.xor_reg(R13, R13)
    _push_bytes_tag(asm, TAG_MAP)
    asm.jmp_label("dispatch")
    asm.label("op_map_put")
    _pop(asm)
    asm.mov_reg_reg(R15, RBX)
    _pop(asm)
    asm.mov_reg_reg(R14, RBX)
    _pop(asm)
    asm.mov_reg_mem(R12, RBX, 8)
    asm.mov_reg_mem(R13, RBX, 16)
    asm.call_label("map_put")
    _push_bytes_tag(asm, TAG_MAP)
    asm.jmp_label("dispatch")
    asm.label("op_map_get")
    _pop(asm)
    asm.mov_reg_reg(R14, RBX)
    _pop(asm)
    asm.mov_reg_mem(R12, RBX, 8)
    asm.mov_reg_mem(R13, RBX, 16)
    asm.call_label("map_find")
    asm.test_reg(RAX, RAX)
    asm.jcc(0x08, "map_get_miss")
    asm.mov_reg_mem(R12, RBP, MAP_PTR)
    asm.shl_reg_imm8(RAX, 6)
    asm.add_reg(R12, RAX)
    asm.add_reg_imm8(R12, 32)
    _slot(asm)
    asm.mov_reg_reg(RCX, RBX)
    asm.mov_reg_reg(RDX, R12)
    asm.mov_reg_imm32(R8, 32)
    asm.call_label("memcpy")
    asm.jmp_label("dispatch")
    asm.label("map_get_miss")
    _fail_empty(asm)
    asm.jmp_label("dispatch")
    asm.label("op_map_has")
    _pop(asm)
    asm.mov_reg_reg(R14, RBX)
    _pop(asm)
    asm.mov_reg_mem(R12, RBX, 8)
    asm.mov_reg_mem(R13, RBX, 16)
    asm.call_label("map_find")
    asm.xor_reg(R12, R12)
    asm.test_reg(RAX, RAX)
    asm.jcc(0x08, "map_has_push")
    asm.mov_reg_imm32(R12, 1)
    asm.label("map_has_push")
    _push_i64(asm)
    asm.jmp_label("dispatch")
    asm.label("op_map_len")
    _pop(asm)
    asm.mov_reg_mem(R12, RBX, 16)
    _i64(asm, RCX, I64_MAX)
    asm.cmp_reg(R12, RCX)
    asm.ja("map_len_fail")
    _push_i64(asm)
    asm.jmp_label("dispatch")
    asm.label("map_len_fail")
    _fail_empty(asm)
    asm.jmp_label("dispatch")
    asm.label("op_map_key")
    _pop(asm)
    asm.mov_reg_mem(R13, RBX, 8)
    _pop(asm)
    asm.mov_reg_mem(R12, RBX, 8)
    asm.mov_reg_mem(R14, RBX, 16)
    asm.test_reg(R13, R13)
    asm.jl("map_key_fail")
    asm.cmp_reg(R13, R14)
    asm.jae("map_key_fail")
    asm.shl_reg_imm8(R13, 6)
    asm.add_reg(R12, R13)
    _slot(asm)
    asm.mov_reg_reg(RCX, RBX)
    asm.mov_reg_reg(RDX, R12)
    asm.mov_reg_imm32(R8, 32)
    asm.call_label("memcpy")
    asm.jmp_label("dispatch")
    asm.label("map_key_fail")
    _fail_empty(asm)
    asm.jmp_label("dispatch")


def write_program(source: Path, exe: Path) -> None:
    exe.parent.mkdir(parents=True, exist_ok=True)
    exe.write_bytes(build_exe(compile_path(source)))
