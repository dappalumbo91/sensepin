"""f64 text for the Sensepin exe.

The digits are the same 17-digit form as format(value, ".17g"), with ".0"
added when that text has no dot and no exponent. Values are scaled with
28 little-endian 64-bit limbs. The widest intermediate seen for finite
f64 is 1131 bits, inside the 1792-bit buffer. No C formatter is called.
"""

from __future__ import annotations

from x64 import RAX, RBP, RBX, RCX, RDX, R8, R9, R10, R11, R12, R13, R14, R15

LIMBS = 28
LIMB_BYTES = LIMBS * 8


def reserve(pe) -> None:
    for name in ("bn0", "bn1", "bn2", "bn4"):
        pe.blob(name, bytes(LIMB_BYTES))
    pe.blob("fbuf", bytes(64))
    pe.blob("fp_digs", bytes(40))
    for name in (
        "fp_sig",
        "fp_exp2",
        "fp_est",
        "fp_sign",
        "fp_quot",
        "fp_bits",
        "fp_ndig",
        "fp_try",
        "fp_scratch",
        "fp_scratch2",
        "fp_low",
    ):
        pe.blob(name, bytes(8))


def _lea(asm, reg: int, name: str) -> None:
    asm.lea_rip(reg, name)


def _store(asm, name: str, reg: int) -> None:
    _lea(asm, R9, name)
    asm.mov_mem_reg(R9, 0, reg)


def _load(asm, reg: int, name: str) -> None:
    _lea(asm, reg, name)
    asm.mov_reg_mem(reg, reg, 0)


def _putc(asm, ch: int) -> None:
    asm.mov_reg_imm32(RAX, ch)
    asm.mov_mem8_reg(R15, 0, RAX)
    asm.inc_reg(R15)


def _digit_at(asm) -> None:
    # Index in rbx. Writes one ASCII digit at r15.
    _lea(asm, R10, "fp_digs")
    asm.add_reg(R10, RBX)
    asm.movzx_reg_byte_mem(RAX, R10, 0)
    asm.add_reg_imm8(RAX, 48)
    asm.mov_mem8_reg(R15, 0, RAX)
    asm.inc_reg(R15)


def _print_down(asm, suffix: str) -> None:
    # rbx is the high index, r14 is the low index, both inclusive.
    asm.label(f"fp_down_{suffix}")
    _digit_at(asm)
    asm.cmp_reg(RBX, R14)
    asm.je(f"fp_down_done_{suffix}")
    asm.dec_reg(RBX)
    asm.jmp_label(f"fp_down_{suffix}")
    asm.label(f"fp_down_done_{suffix}")


def _zeros(asm, suffix: str) -> None:
    # Count in r11. _putc keeps r11.
    asm.label(f"fp_z_{suffix}")
    asm.test_reg(R11, R11)
    asm.jz(f"fp_z_done_{suffix}")
    _putc(asm, ord("0"))
    asm.dec_reg(R11)
    asm.jmp_label(f"fp_z_{suffix}")
    asm.label(f"fp_z_done_{suffix}")


def _msd(asm) -> None:
    asm.mov_reg_reg(RBX, R14)
    asm.add_reg(RBX, R12)
    asm.dec_reg(RBX)


def emit(asm, sp: int, cells: int, tag_bytes: int) -> None:
    _bn(asm)
    asm.label("dec_f64")
    asm.mov_reg_reg(RAX, R12)
    asm.mov_reg_imm64(RCX, 0x7FFFFFFFFFFFFFFF)
    asm.and_reg(RAX, RCX)
    asm.jz("fp_zero")
    asm.mov_reg_reg(RAX, R12)
    asm.shr_reg_imm8(RAX, 63)
    _store(asm, "fp_sign", RAX)
    asm.mov_reg_reg(RAX, R12)
    asm.mov_reg_imm64(RCX, 0x7FFFFFFFFFFFFFFF)
    asm.and_reg(RAX, RCX)
    _store(asm, "fp_bits", RAX)
    asm.mov_reg_reg(RCX, RAX)
    asm.shr_reg_imm8(RCX, 52)
    asm.mov_reg_imm32(RDX, 0x7FF)
    asm.and_reg(RCX, RDX)
    asm.mov_reg_reg(RDX, RAX)
    asm.mov_reg_imm64(R8, (1 << 52) - 1)
    asm.and_reg(RDX, R8)
    asm.test_reg(RCX, RCX)
    asm.jz("fp_sub")
    asm.mov_reg_imm64(R8, 1 << 52)
    asm.or_reg(RDX, R8)
    _store(asm, "fp_sig", RDX)
    asm.mov_reg_imm32(R8, 1075)
    asm.sub_reg(RCX, R8)
    _store(asm, "fp_exp2", RCX)
    asm.mov_reg_reg(RAX, RCX)
    asm.add_reg_imm8(RAX, 52)
    asm.call_label("fp_floordiv")
    _store(asm, "fp_est", RAX)
    asm.jmp_label("fp_try0")
    asm.label("fp_sub")
    _store(asm, "fp_sig", RDX)
    asm.mov_reg_imm32(RCX, 1074)
    asm.neg_reg(RCX)
    _store(asm, "fp_exp2", RCX)
    asm.bsr_reg(RAX, RDX)
    asm.mov_reg_imm32(RCX, 1074)
    asm.sub_reg(RAX, RCX)
    asm.call_label("fp_floordiv")
    _store(asm, "fp_est", RAX)
    asm.label("fp_try0")
    asm.xor_reg(RAX, RAX)
    _store(asm, "fp_try", RAX)
    asm.label("fp_attempt")
    _load(asm, RAX, "fp_try")
    asm.inc_reg(RAX)
    _store(asm, "fp_try", RAX)
    asm.cmp_reg_imm8(RAX, 5)
    asm.jg("fp_format")
    _build(asm)
    _divmod(asm)
    _round(asm)
    _digits(asm)
    _load(asm, RAX, "fp_ndig")
    asm.cmp_reg_imm8(RAX, 17)
    asm.je("fp_format")
    asm.mov_reg_imm32(RDX, 17)
    asm.sub_reg(RAX, RDX)
    _load(asm, RCX, "fp_est")
    asm.add_reg(RCX, RAX)
    _store(asm, "fp_est", RCX)
    asm.jmp_label("fp_attempt")
    asm.label("fp_format")
    _format(asm)
    asm.label("fp_zero")
    _lea(asm, R15, "fbuf")
    _putc(asm, ord("0"))
    _putc(asm, ord("."))
    _putc(asm, ord("0"))
    asm.label("fp_emit")
    _emit_text(asm, sp, cells, tag_bytes)
    asm.label("fp_floordiv")
    # rax = floor(n * 30103 / 100000), with floor for a negative n.
    asm.mov_reg_reg(R10, RAX)
    asm.mov_reg_imm32(RCX, 30103)
    asm.imul_reg(RAX, RCX)
    asm.cqo()
    asm.mov_reg_imm32(RCX, 100000)
    asm.idiv_reg(RCX)
    asm.test_reg(R10, R10)
    asm.jge("fp_floor_done")
    asm.test_reg(RDX, RDX)
    asm.jz("fp_floor_done")
    asm.dec_reg(RAX)
    asm.label("fp_floor_done")
    asm.ret()


def _emit_text(asm, sp: int, cells: int, tag_bytes: int) -> None:
    _lea(asm, R12, "fbuf")
    asm.mov_reg_reg(R13, R15)
    asm.sub_reg(R13, R12)
    asm.mov_reg_reg(RCX, R13)
    asm.call_label("alloc")
    _store(asm, "fp_scratch", RAX)
    asm.mov_reg_reg(RCX, RAX)
    _lea(asm, RDX, "fbuf")
    asm.mov_reg_reg(R8, R13)
    asm.call_label("memcpy")
    _load(asm, R12, "fp_scratch")
    asm.mov_reg_mem(RAX, RBP, sp)
    asm.shl_reg_imm8(RAX, 5)
    asm.mov_reg_mem(RBX, RBP, cells)
    asm.add_reg(RBX, RAX)
    asm.inc_mem(RBP, sp)
    asm.mov_reg_imm64(R14, tag_bytes)
    asm.mov_mem_reg(RBX, 0, R14)
    asm.mov_mem_reg(RBX, 8, R12)
    asm.mov_mem_reg(RBX, 16, R13)
    asm.xor_reg(RAX, RAX)
    asm.mov_mem_reg(RBX, 24, RAX)
    asm.jmp_label("dispatch")


def _build(asm) -> None:
    asm.xor_reg(RAX, RAX)
    _store(asm, "fp_low", RAX)
    _lea(asm, RCX, "bn0")
    _load(asm, RDX, "fp_sig")
    asm.call_label("bn_setu")
    _lea(asm, RCX, "bn1")
    asm.mov_reg_imm32(RDX, 1)
    asm.call_label("bn_setu")
    _load(asm, RAX, "fp_exp2")
    asm.test_reg(RAX, RAX)
    asm.jz("fp_scale")
    asm.jg("fp_exp_pos")
    asm.neg_reg(RAX)
    asm.mov_reg_reg(R8, RAX)
    _lea(asm, RCX, "bn2")
    _lea(asm, RDX, "bn1")
    asm.call_label("bn_shl")
    _lea(asm, RCX, "bn1")
    _lea(asm, RDX, "bn2")
    asm.call_label("bn_copy")
    asm.jmp_label("fp_scale")
    asm.label("fp_exp_pos")
    asm.mov_reg_reg(R8, RAX)
    _lea(asm, RCX, "bn2")
    _lea(asm, RDX, "bn0")
    asm.call_label("bn_shl")
    _lea(asm, RCX, "bn0")
    _lea(asm, RDX, "bn2")
    asm.call_label("bn_copy")
    asm.label("fp_scale")
    _load(asm, RAX, "fp_est")
    asm.mov_reg_imm32(RCX, 16)
    asm.sub_reg(RCX, RAX)
    asm.test_reg(RCX, RCX)
    asm.jz("fp_build_done")
    asm.jg("fp_scale_pos")
    asm.neg_reg(RCX)
    asm.mov_reg_reg(RDX, RCX)
    _lea(asm, RCX, "bn1")
    asm.call_label("bn_mul10_pow")
    asm.jmp_label("fp_build_done")
    asm.label("fp_scale_pos")
    asm.mov_reg_reg(RDX, RCX)
    _lea(asm, RCX, "bn0")
    asm.call_label("bn_mul10_pow")
    asm.label("fp_build_done")


def _divmod(asm) -> None:
    _lea(asm, RCX, "bn0")
    _lea(asm, RDX, "bn1")
    asm.call_label("bn_divmod")


def _round(asm) -> None:
    _load(asm, RAX, "fp_low")
    asm.test_reg(RAX, RAX)
    asm.jnz("fp_round_done")
    _lea(asm, RCX, "bn4")
    _lea(asm, RDX, "bn0")
    asm.mov_reg_imm32(R8, 1)
    asm.call_label("bn_shl")
    _lea(asm, RCX, "bn4")
    _lea(asm, RDX, "bn1")
    asm.call_label("bn_cmp")
    asm.cmp_reg_imm8(RAX, 1)
    asm.je("fp_round_up")
    asm.cmp_reg_imm8(RAX, 0)
    asm.jne("fp_round_done")
    _load(asm, RAX, "fp_quot")
    asm.mov_reg_imm32(RCX, 1)
    asm.test_reg(RAX, RCX)
    asm.jz("fp_round_done")
    asm.label("fp_round_up")
    _load(asm, RAX, "fp_quot")
    asm.inc_reg(RAX)
    _store(asm, "fp_quot", RAX)
    asm.label("fp_round_done")


def _digits(asm) -> None:
    _load(asm, RAX, "fp_low")
    asm.test_reg(RAX, RAX)
    asm.jnz("fp_digits_big")
    _load(asm, RAX, "fp_quot")
    _lea(asm, R15, "fp_digs")
    asm.xor_reg(RBX, RBX)
    asm.test_reg(RAX, RAX)
    asm.jnz("fp_digits_loop")
    asm.xor_reg(RDX, RDX)
    asm.mov_mem8_reg(R15, 0, RDX)
    asm.mov_reg_imm32(RAX, 1)
    _store(asm, "fp_ndig", RAX)
    asm.jmp_label("fp_digits_done")
    asm.label("fp_digits_loop")
    asm.xor_reg(RDX, RDX)
    asm.mov_reg_imm32(RCX, 10)
    asm.udiv_reg(RCX)
    asm.mov_reg_reg(R11, R15)
    asm.add_reg(R11, RBX)
    asm.mov_mem8_reg(R11, 0, RDX)
    asm.inc_reg(RBX)
    asm.test_reg(RAX, RAX)
    asm.jnz("fp_digits_loop")
    _store(asm, "fp_ndig", RBX)
    asm.jmp_label("fp_digits_done")
    asm.label("fp_digits_big")
    asm.mov_reg_imm32(RAX, 19)
    _store(asm, "fp_ndig", RAX)
    asm.label("fp_digits_done")


def _format(asm) -> None:
    # r12 = significant digits, r13 = decimal exponent, r14 = low index.
    _load(asm, RAX, "fp_est")
    _load(asm, RCX, "fp_ndig")
    asm.add_reg(RAX, RCX)
    asm.sub_reg_imm8(RAX, 17)
    asm.mov_reg_reg(R13, RAX)
    asm.xor_reg(R14, R14)
    _load(asm, R12, "fp_ndig")
    asm.label("fp_strip")
    asm.mov_reg_reg(RAX, R12)
    asm.dec_reg(RAX)
    asm.cmp_reg(R14, RAX)
    asm.jge("fp_strip_done")
    _lea(asm, R10, "fp_digs")
    asm.add_reg(R10, R14)
    asm.movzx_reg_byte_mem(RAX, R10, 0)
    asm.test_reg(RAX, RAX)
    asm.jnz("fp_strip_done")
    asm.inc_reg(R14)
    asm.jmp_label("fp_strip")
    asm.label("fp_strip_done")
    _load(asm, RAX, "fp_ndig")
    asm.mov_reg_reg(R12, RAX)
    asm.sub_reg(R12, R14)
    _lea(asm, R15, "fbuf")
    _load(asm, RAX, "fp_sign")
    asm.test_reg(RAX, RAX)
    asm.jz("fp_nosign")
    _putc(asm, ord("-"))
    asm.label("fp_nosign")
    asm.cmp_reg_imm8(R13, -4)
    asm.jl("fp_sci")
    asm.cmp_reg_imm8(R13, 17)
    asm.jge("fp_sci")
    asm.test_reg(R13, R13)
    asm.jl("fp_frac")
    asm.mov_reg_reg(RAX, R12)
    asm.dec_reg(RAX)
    asm.cmp_reg(R13, RAX)
    asm.jge("fp_fixed_int")
    _msd(asm)
    asm.mov_reg_reg(R11, R13)
    asm.inc_reg(R11)
    asm.label("fp_mixed_left")
    _digit_at(asm)
    asm.dec_reg(RBX)
    asm.dec_reg(R11)
    asm.jnz("fp_mixed_left")
    _putc(asm, ord("."))
    _print_down(asm, "mixed")
    asm.jmp_label("fp_emit")
    asm.label("fp_fixed_int")
    _msd(asm)
    _print_down(asm, "int")
    asm.mov_reg_reg(R11, R13)
    asm.sub_reg(R11, R12)
    asm.inc_reg(R11)
    _zeros(asm, "int")
    _putc(asm, ord("."))
    _putc(asm, ord("0"))
    asm.jmp_label("fp_emit")
    asm.label("fp_frac")
    _putc(asm, ord("0"))
    _putc(asm, ord("."))
    asm.mov_reg_reg(R11, R13)
    asm.neg_reg(R11)
    asm.dec_reg(R11)
    _zeros(asm, "frac")
    _msd(asm)
    _print_down(asm, "frac")
    asm.jmp_label("fp_emit")
    asm.label("fp_sci")
    _msd(asm)
    _digit_at(asm)
    asm.cmp_reg_imm8(R12, 1)
    asm.jle("fp_sci_exp")
    _putc(asm, ord("."))
    asm.dec_reg(RBX)
    _print_down(asm, "sci")
    asm.label("fp_sci_exp")
    _putc(asm, ord("e"))
    asm.test_reg(R13, R13)
    asm.jl("fp_sci_neg")
    _putc(asm, ord("+"))
    asm.mov_reg_reg(RAX, R13)
    asm.jmp_label("fp_sci_abs")
    asm.label("fp_sci_neg")
    _putc(asm, ord("-"))
    asm.mov_reg_reg(RAX, R13)
    asm.neg_reg(RAX)
    asm.label("fp_sci_abs")
    _lea(asm, R10, "fp_scratch")
    asm.xor_reg(RBX, RBX)
    asm.label("fp_exp_div")
    asm.xor_reg(RDX, RDX)
    asm.mov_reg_imm32(RCX, 10)
    asm.udiv_reg(RCX)
    asm.add_reg_imm8(RDX, 48)
    asm.mov_reg_reg(R11, R10)
    asm.add_reg(R11, RBX)
    asm.mov_mem8_reg(R11, 0, RDX)
    asm.inc_reg(RBX)
    asm.test_reg(RAX, RAX)
    asm.jnz("fp_exp_div")
    asm.cmp_reg_imm8(RBX, 1)
    asm.jne("fp_exp_out")
    asm.mov_reg_reg(R11, R10)
    asm.add_reg(R11, RBX)
    asm.mov_reg_imm32(RAX, ord("0"))
    asm.mov_mem8_reg(R11, 0, RAX)
    asm.inc_reg(RBX)
    asm.label("fp_exp_out")
    asm.label("fp_exp_rev")
    asm.dec_reg(RBX)
    asm.mov_reg_reg(R11, R10)
    asm.add_reg(R11, RBX)
    asm.movzx_reg_byte_mem(RAX, R11, 0)
    asm.mov_mem8_reg(R15, 0, RAX)
    asm.inc_reg(R15)
    asm.test_reg(RBX, RBX)
    asm.jnz("fp_exp_rev")
    asm.jmp_label("fp_emit")


def _bn(asm) -> None:
    asm.label("bn_zero")
    asm.mov_reg_reg(R9, RCX)
    asm.mov_reg_imm32(R10, LIMBS)
    asm.label("bn_zero_loop")
    asm.xor_reg(RAX, RAX)
    asm.mov_mem_reg(R9, 0, RAX)
    asm.add_reg_imm8(R9, 8)
    asm.dec_reg(R10)
    asm.jnz("bn_zero_loop")
    asm.ret()
    asm.label("bn_setu")
    asm.call_label("bn_zero")
    asm.mov_mem_reg(RCX, 0, RDX)
    asm.ret()
    asm.label("bn_copy")
    asm.mov_reg_imm32(R9, LIMBS)
    asm.label("bn_copy_loop")
    asm.mov_reg_mem(RAX, RDX, 0)
    asm.mov_mem_reg(RCX, 0, RAX)
    asm.add_reg_imm8(RDX, 8)
    asm.add_reg_imm8(RCX, 8)
    asm.dec_reg(R9)
    asm.jnz("bn_copy_loop")
    asm.ret()
    asm.label("bn_shl")
    asm.test_reg(R8, R8)
    asm.jz("bn_copy")
    asm.mov_reg_reg(R11, R8)
    asm.shr_reg_imm8(R11, 6)
    asm.and_reg_imm8(R8, 63)
    asm.cmp_reg_imm8(R11, LIMBS)
    asm.jb("bn_shl_ok")
    asm.jmp_label("bn_zero")
    asm.label("bn_shl_ok")
    asm.call_label("bn_zero")
    asm.mov_reg_reg(R10, RDX)
    asm.mov_reg_reg(R9, RCX)
    asm.mov_reg_reg(RAX, R11)
    asm.shl_reg_imm8(RAX, 3)
    asm.add_reg(R9, RAX)
    asm.mov_reg_imm32(RAX, LIMBS)
    asm.sub_reg(RAX, R11)
    asm.mov_reg_reg(R11, RAX)
    asm.label("bn_shl_copy")
    asm.test_reg(R11, R11)
    asm.jz("bn_shl_bits")
    asm.mov_reg_mem(RAX, R10, 0)
    asm.mov_mem_reg(R9, 0, RAX)
    asm.add_reg_imm8(R10, 8)
    asm.add_reg_imm8(R9, 8)
    asm.dec_reg(R11)
    asm.jmp_label("bn_shl_copy")
    asm.label("bn_shl_bits")
    asm.test_reg(R8, R8)
    asm.jz("bn_shl_ret")
    asm.mov_reg_reg(R10, RCX)
    asm.xor_reg(R9, R9)
    asm.mov_reg_imm32(R11, LIMBS)
    asm.label("bn_shl_bit")
    asm.mov_reg_mem(RAX, R10, 0)
    asm.mov_reg_reg(RDX, RAX)
    asm.mov_reg_imm32(RCX, 64)
    asm.sub_reg(RCX, R8)
    asm.shr_reg_cl(RDX)
    asm.mov_reg_reg(RCX, R8)
    asm.shl_reg_cl(RAX)
    asm.or_reg(RAX, R9)
    asm.mov_mem_reg(R10, 0, RAX)
    asm.mov_reg_reg(R9, RDX)
    asm.add_reg_imm8(R10, 8)
    asm.dec_reg(R11)
    asm.jnz("bn_shl_bit")
    asm.label("bn_shl_ret")
    asm.ret()
    asm.label("bn_mul10")
    asm.mov_reg_reg(R10, RCX)
    asm.xor_reg(R9, R9)
    asm.mov_reg_imm32(R11, LIMBS)
    asm.label("bn_mul10_loop")
    asm.mov_reg_mem(RAX, R10, 0)
    asm.mov_reg_imm32(RCX, 10)
    asm.mul_reg(RCX)
    asm.add_reg(RAX, R9)
    asm.adc_reg_imm8(RDX, 0)
    asm.mov_mem_reg(R10, 0, RAX)
    asm.mov_reg_reg(R9, RDX)
    asm.add_reg_imm8(R10, 8)
    asm.dec_reg(R11)
    asm.jnz("bn_mul10_loop")
    asm.test_reg(R9, R9)
    asm.jnz("oom")
    asm.ret()
    asm.label("bn_mul10_pow")
    _store(asm, "fp_scratch", RCX)
    _store(asm, "fp_scratch2", RDX)
    asm.label("bn_pow_loop")
    _load(asm, RAX, "fp_scratch2")
    asm.test_reg(RAX, RAX)
    asm.jz("bn_pow_done")
    _load(asm, RCX, "fp_scratch")
    asm.call_label("bn_mul10")
    _load(asm, RAX, "fp_scratch2")
    asm.dec_reg(RAX)
    _store(asm, "fp_scratch2", RAX)
    asm.jmp_label("bn_pow_loop")
    asm.label("bn_pow_done")
    asm.ret()
    asm.label("bn_cmp")
    asm.mov_reg_reg(R10, RCX)
    asm.mov_reg_reg(R11, RDX)
    asm.add_reg_imm32(R10, (LIMBS - 1) * 8)
    asm.add_reg_imm32(R11, (LIMBS - 1) * 8)
    asm.mov_reg_imm32(R9, LIMBS)
    asm.label("bn_cmp_loop")
    asm.mov_reg_mem(RAX, R10, 0)
    asm.mov_reg_mem(RDX, R11, 0)
    asm.cmp_reg(RAX, RDX)
    asm.ja("bn_cmp_gt")
    asm.jb("bn_cmp_lt")
    asm.sub_reg_imm8(R10, 8)
    asm.sub_reg_imm8(R11, 8)
    asm.dec_reg(R9)
    asm.jnz("bn_cmp_loop")
    asm.xor_reg(RAX, RAX)
    asm.ret()
    asm.label("bn_cmp_gt")
    asm.mov_reg_imm32(RAX, 1)
    asm.ret()
    asm.label("bn_cmp_lt")
    asm.mov_reg_imm32(RAX, 2)
    asm.ret()
    asm.label("bn_sub")
    asm.mov_reg_reg(R10, RCX)
    asm.mov_reg_reg(R11, RDX)
